/* ---- frame capture (Ctrl+Alt+Help) --------------------------------------
 * One box frame, as it went out: every timed write with its line, cycle
 * and how late it left; for every displayed line, how many longs of what
 * it shows were still not copied to the real RAM when the real beam got
 * there; and the box's own picture of the frame (stboxmetal-frame-N.ppm,
 * borders included) - what the real monitor should have shown. */
static uint64_t *g_dirty;                   /* RAM mirroring, below */
static uint32_t  g_ram_bytes;
#define CW 8192
typedef struct { uint16_t line; int16_t lcyc; uint32_t a; uint16_t v; uint8_t burst; int32_t late_ns; uint32_t pc; } cw_t;
typedef struct { uint64_t abs_line; uint32_t vcnt; uint16_t line, bytes; int16_t fstart; int16_t stale; } cl_t;
static struct {
    volatile int req;                       /* hotkey: capture next frame */
    int      state;                         /* 0 idle, 1 armed, 2 on, 3 box
                                               done, 4 picture taken, 5
                                               all out: report             */
    uint32_t frame, arm_frame;              /* box frame being captured   */
    unsigned nw, nl, chk, n;
    cw_t     w[CW];
    cl_t     l[320];
    stbox_cap_t pic;                        /* the box's picture of it    */
    int      have_pic;
} FC;
static void fc_line(uint64_t abs_line, unsigned line, int fstart, unsigned bytes, uint32_t vcnt)
{
    if (FC.state == 1 && stbox_shared.frame != FC.arm_frame) {
        FC.state = 2; FC.frame = stbox_shared.frame; FC.nw = FC.nl = FC.chk = 0;
    }
    if (FC.state != 2) return;
    if (stbox_shared.frame != FC.frame) {   /* the next frame began: done */
        FC.state = 3;
        return;
    }
    if (FC.nl < 320)
        FC.l[FC.nl++] = (cl_t){ abs_line, vcnt, (uint16_t)line, (uint16_t)bytes, (int16_t)fstart, -1 };
}
/* bus thread: the beam has reached the start of line k - what is stale? */
static void fc_check(double now)
{
    while (FC.chk < FC.nl && m_time((double)(FC.l[FC.chk].abs_line + (uint64_t)FC.l[FC.chk].fstart) + g_cal) <= now) {
        cl_t *c = &FC.l[FC.chk++];
        int st = 0;
        for (uint32_t o = c->vcnt & ~3u; o < c->vcnt + c->bytes && o < g_ram_bytes; o += 4)
            if (g_dirty[o >> 8] & (1ull << ((o >> 2) & 63))) st++;
        c->stale = (int16_t)st;
    }
}
#define MQ (1u << 16)
static mev_t    mq[MQ];
static unsigned mq_r, mq_w;

/* The vertical border decision (cycle 502 of lines 33, 62, 233, 262 in
 * the box's GLUE): a sync/resolution write a few cycles either side of it
 * opens or keeps a border, and a landing error of a cycle or two puts it
 * on the wrong side on the real GLUE (run 4: Defender's 50 Hz write at
 * cycle 504 of line 262 kept the bottom border open on only 90 % of
 * frames). Such a write is moved, if need be, to land at least
 * VMARGIN cycles on the same side of the REAL decision as it is of the
 * box's: g_vdec = the last cycle that still counts as before it on the
 * real ST (measured at start-up, beamtest's F sweep). */
#define VMARGIN 3
static double g_vdec = 502.0;
static int    vdec_forced;
static uint64_t g_vmoved;

static uint64_t g_last_abs;
static void m_hw(uint64_t abs, uint32_t a, uint32_t v, int size, unsigned line, int lcyc)
{
    if ((a == 0xFF820A || a == 0xFF8260) && (line == 33 || line == 62 || line == 233 || line == 262) &&
        lcyc >= 502 - 32 && lcyc <= 502 + 32) {
        double tgt = lcyc;
        if (lcyc <= 502) { if (tgt > g_vdec - VMARGIN) tgt = floor(g_vdec - VMARGIN); }
        else             { if (tgt < g_vdec + 1 + VMARGIN) tgt = ceil(g_vdec + 1 + VMARGIN); }
        if (tgt != lcyc) { abs = (uint64_t)((int64_t)abs + (int64_t)(tgt - lcyc)); g_vmoved++; }
    }
    /* writes are at least a bus cycle apart: Musashi stamps every write
     * of one instruction (movem to the palette) with the same cycle */
    if (abs < g_last_abs + 4 && g_last_abs - abs < 1024) abs = g_last_abs + 4;
    g_last_abs = abs;
    if (mq_w - mq_r >= MQ) { M.q_drop++; return; }
    mq[mq_w & (MQ - 1)] = (mev_t){ abs, a, (uint16_t)v, (uint8_t)size,
                                   (uint8_t)(FC.state == 2 && stbox_shared.frame == FC.frame),
                                   (uint16_t)line, (int16_t)lcyc,
                                   FC.state == 2 ? m68k_get_reg(NULL, M68K_REG_PPC) : 0 };
    mq_w++;
    if (mq_w - mq_r > M.q_max) M.q_max = mq_w - mq_r;
}

/* ---- lock tracking: one real counter read a frame ---------------------- */
typedef struct { uint64_t abs_line; unsigned line; int fstart; unsigned bytes; uint32_t vcnt; } mline_t;
static struct {
    int      pending;                       /* a read scheduled           */
    uint64_t abs;                           /* where                      */
    mline_t  ln;                            /* the line it is on          */
    uint64_t last_abs;                      /* last good read             */
    int      rej_run, coarse_n;
    double   coarse_e;
    uint32_t frame_seen;                    /* box frame of the last one  */
} P1;

static void v_line(uint64_t abs_line, unsigned line, int fstart, unsigned bytes, uint32_t vcnt);
static void m_line(uint64_t abs_line, unsigned line, int fstart, unsigned bytes, uint32_t vcnt)
{
    v_line(abs_line, line, fstart, bytes, vcnt);
    if (FC.state) fc_line(abs_line, line, fstart, bytes, vcnt);
    /* one read a box frame, mid-line on a plain-ish displayed line, where
     * no timed write is queued within 64 cycles of it */
    if (P1.pending || P1.frame_seen == stbox_shared.frame) return;
    if (bytes < 160 || fstart > 56 || line < 40) return;
    const uint64_t at = abs_line + (uint64_t)fstart + 64u + (uint64_t)(P1.frame_seen & 3);
    for (unsigned j = mq_w; j != mq_r; ) {
        j--;
        const mev_t *e = &mq[j & (MQ - 1)];
        if (e->abs + 64 < at) break;
        if (e->abs <= at + 64) { M.probe_skip++; return; }
    }
    P1.pending = 1;
    P1.abs = at;
    P1.ln = (mline_t){ abs_line, line, fstart, bytes, vcnt };
    P1.frame_seen = stbox_shared.frame;
}

static double g_plead_ns;                    /* lock read start -> its stamp */
static void m_probe(void)
{
    P1.pending = 0;
    M.probes++;
    uint32_t cnt; uint64_t t;
    const double due = m_time((double)P1.abs);
    const uint64_t p0 = ticks();
    if (!read_counter(&cnt, &t)) { M.probe_rej++; P1.rej_run++; return; }
    /* the read's stamp is the middle of the counter's low byte, two bus
     * reads after the start: ~1.2 us on a Pi 4 but ~3 us on a 3A+, where
     * every read came out "late" (2 of 250 a second used) and the lock
     * drifted to 6 cycles sd. Learn that time and start the read that
     * much early (main loop), so the stamp itself lands on time. */
    {
        const double ov = (double)(t - p0) * NSPT;
        if (ov > 0 && ov < 8000.0) g_plead_ns = g_plead_ns > 0 ? 0.9 * g_plead_ns + 0.1 * ov : ov;
    }
    if (((double)t - due) * NSPT > 2000.0) { M.probe_late++; return; }
    const long off = (long)cnt - (long)P1.ln.vcnt;
    if (off <= 0 || off >= (long)P1.ln.bytes) {
        /* The real beam is not on the box's line: a late write made the
         * real GLUE do something the box's didn't (run 3: one did, and
         * the lock never came back - every write after it landed lines
         * away). Take whole lines of the box's width from the byte
         * difference; four reads in a row within 32 cycles of each other
         * move the map there, and the fine loop takes over. */
        M.probe_rej++; P1.rej_run++;
        const long B = (long)P1.ln.bytes;
        const long ln = off >= 0 ? off / B : -((-off + B - 1) / B), rem = off - ln * B;
        const double abs_r = (double)P1.ln.abs_line + P1.ln.fstart + 2.0 * rem + 2.0 + (double)ln * 512.0;
        const double ec = m_abs((double)t) - abs_r;
        if (P1.coarse_n && fabs(ec - P1.coarse_e) < 32.0) P1.coarse_n++;
        else { P1.coarse_n = 1; P1.coarse_e = ec; }
        if (P1.coarse_n >= 4 && fabs(ec) < 160256.0) {
            mT0 += ec * TPC;
            P1.coarse_n = 0; P1.rej_run = 0; P1.last_abs = 0;
            M.relocks++;
        }
        return;
    }
    P1.coarse_n = 0;
    const double abs_true = (double)P1.ln.abs_line + P1.ln.fstart + 2.0 * off + 2.0;
    const double e = m_abs((double)t) - abs_true;      /* + = map runs early */
    if (fabs(e) > 64.0) {
        M.probe_rej++;
        if (++P1.rej_run >= 8) {              /* trust the counter        */
            mT0 += e * TPC; P1.rej_run = 0; M.relocks++;
        }
        return;
    }
    P1.rej_run = 0;
    M.probe_ok++; M.e_sum += e; M.e_sq += e * e;
    if (fabs(e) > M.e_max) M.e_max = fabs(e);
    /* shifter_mirror.c's loop: phase a quarter (all beyond 8 cycles),
     * rate a sixteenth spread over the cycles since the last good read;
     * re-anchored at this read so a new rate moves nothing behind it */
    const double Tn = m_time(abs_true) + (fabs(e) > 8.0 ? e : e / 4.0) * TPC;
    if (P1.last_abs && abs_true > (double)P1.last_abs) {
        const double dc = abs_true - (double)P1.last_abs;
        if (dc < 4.0 * 160256.0) TPC += e * TPC / 16.0 / dc;
    }
    mA0 = (uint64_t)abs_true;
    mT0 = Tn - (abs_true - (double)mA0) * TPC;
    P1.last_abs = (uint64_t)abs_true;
}

/* ---- top/bottom border checks ------------------------------------------
 * Twice a frame the real counter is read on a line where the box's GLUE
 * says the real one must be displaying: two lines into the box's first
 * displayed line (its top border open or not) and line 268 when the box
 * opened the bottom border. A mismatch is a frame where the real ST did
 * not do what the box did; the reporter prints, for the first ones, the
 * sync/resolution writes made around those lines and how late each
 * landed - the data for whatever window the real GLUE has there. */
enum { V_TOP, V_BOT };
static struct { int pending; uint64_t abs; mline_t ln; int tag, box_open; } PV[2];
static uint32_t v_frame = 0xFFFFFFFFu;
static unsigned v_first;                     /* box's first DE line      */
static uint64_t v_frame_abs;

/* executed sync/resolution writes, for the reports */
typedef struct { uint64_t abs; uint8_t a, v; int16_t late10; } xw_t;
#define XW 1024
static xw_t xw[XW];
static unsigned xw_n;

typedef struct {
    uint32_t frame; uint8_t tag, box_open, nw; uint16_t first, line;
    int32_t real_off, model_off;
    struct { int16_t line, cyc, late10; uint8_t a, v; } w[16];
} vcase_t;
#define VC 16
static vcase_t vc[VC];
static volatile unsigned vc_w, vc_r;

static int v_free(uint64_t at)               /* no queued write near it  */
{
    for (unsigned j = mq_w; j != mq_r; ) {
        j--;
        const mev_t *e = &mq[j & (MQ - 1)];
        if (e->abs + 64 < at) break;
        if (e->abs <= at + 64) return 0;
    }
    return 1;
}

static void v_line(uint64_t abs_line, unsigned line, int fstart, unsigned bytes, uint32_t vcnt)
{
    if (stbox_shared.frame != v_frame) {     /* first displayed line     */
        v_frame = stbox_shared.frame;
        v_first = line;
        v_frame_abs = abs_line - (uint64_t)line * 512u;
    }
    const int top = line == v_first + 2, bot = line == 268;
    if (!top && !bot) return;
    const int k = top ? V_TOP : V_BOT;
    if (PV[k].pending || bytes < 160) return;
    const uint64_t at = abs_line + (uint64_t)fstart + 72u;
    if (!v_free(at)) { M.probe_skip++; return; }
    PV[k] = (typeof(PV[k])){ 1, at, { abs_line, line, fstart, bytes, vcnt }, k, v_first < 63 };
}

static void v_probe(int k)
{
    PV[k].pending = 0;
    uint32_t cnt; uint64_t t;
    if (!read_counter(&cnt, &t)) return;
    const double cin = m_abs((double)t) - (double)PV[k].ln.abs_line;
    const long model = lround((cin - PV[k].ln.fstart - 2.0) / 2.0) & ~1L;
    const long off = (long)cnt - (long)PV[k].ln.vcnt;
    const int ok = off > 0 && off < (long)PV[k].ln.bytes && labs(off - model) <= 8;
    if (k == V_TOP) { M.top_n[PV[k].box_open]++; M.top_ok[PV[k].box_open] += ok; }
    else            { M.bot_n++; M.bot_ok += ok; }
    if (ok) return;
    /* the first 8 of each kind since the last reset, then 1 in 250 */
    if (++M.case_n[k] > 8 && M.case_n[k] % 250) return;
    if (vc_w - vc_r >= VC) return;
    vcase_t *c = &vc[vc_w & (VC - 1)];
    memset(c, 0, sizeof *c);
    c->frame = v_frame; c->tag = (uint8_t)k; c->box_open = (uint8_t)PV[k].box_open;
    c->first = (uint16_t)v_first; c->line = (uint16_t)PV[k].ln.line;
    c->real_off = (int32_t)off; c->model_off = (int32_t)model;
    /* the writes around the decision (vertical DE is decided at cycle
     * 502 of line 33 / 262), oldest first: back to the window's start,
     * then forward */
    const int l0 = k == V_TOP ? 31 : 260, l1 = k == V_TOP ? 34 : 263;
    unsigned j = xw_n;
    while (j != xw_n - XW) {
        const xw_t *x = &xw[(j - 1) & (XW - 1)];
        if (x->abs < v_frame_abs || (x->abs - v_frame_abs) / 512u < (uint64_t)l0) break;
        j--;
    }
    for (; j != xw_n && c->nw < 16; j++) {
        const xw_t *x = &xw[j & (XW - 1)];
        const uint64_t d = x->abs - v_frame_abs;
        const int L = (int)(d / 512u), cy = (int)(d % 512u);
        if (L < l0 || L > l1 || (L == l1 && cy > 100)) continue;
        c->w[c->nw].line = (int16_t)L; c->w[c->nw].cyc = (int16_t)cy;
        c->w[c->nw].a = x->a; c->w[c->nw].v = x->v; c->w[c->nw].late10 = x->late10;
        c->nw++;
    }
    __atomic_thread_fence(__ATOMIC_RELEASE);
    vc_w++;
}

/* ---- RAM: the box's writes, copied to the real ST-RAM ------------------ */
static uint64_t *g_dirty;
static uint8_t  *g_blk;
static uint32_t  g_ram_bytes;
static uint32_t  g_cur_scr, g_cur_all;       /* scan cursors              */

/* Next dirty long in [lo, hi): blocks in order from the one *cur is in,
 * wrapping, lowest address first inside a block. A block found with no
 * bit left is marked clean. -1 = nothing dirty in the range. */
static long dirty_next(uint32_t lo, uint32_t hi, uint32_t *cur)
{
    if (hi <= lo) return -1;
    const uint32_t blo = lo >> 14, bhi = (hi - 1) >> 14;
    uint32_t b = (*cur >= lo && *cur < hi) ? (*cur >> 14) : blo;
    for (uint32_t i = 0; i <= bhi - blo; i++) {
        if (g_blk[b]) {
            int any = 0;
            for (uint32_t w = b << 6; w < (b + 1) << 6; w++) {
                uint64_t m = g_dirty[w];
                if (!m) continue;
                any = 1;
                while (m) {
                    const uint32_t o = (w << 8) + 4u * (uint32_t)__builtin_ctzll(m);
                    if (o >= lo && o < hi) { *cur = o; return (long)o; }
                    m &= m - 1;
                }
            }
            if (!any) g_blk[b] = 0;
        }
        b = b == bhi ? blo : b + 1;
    }
    return -1;
}

static int flush_one(void)
{
    if (!stbox_metal_any) return 0;
    const uint32_t vb = stbox_shared.video_base & (g_ram_bytes - 1) & ~0xFFu;
    uint32_t hi = vb + 0x10000u; if (hi > g_ram_bytes) hi = g_ram_bytes;
    long o = dirty_next(vb, hi, &g_cur_scr);
    if (o < 0) o = dirty_next(0, g_ram_bytes, &g_cur_all);
    if (o < 0) { stbox_metal_any = 0; return 0; }
    g_dirty[o >> 8] &= ~(1ull << ((o >> 2) & 63));
    const uint8_t *p = stbox_shared.ram + o;
    ps_write_32((uint32_t)o, ((uint32_t)p[0] << 24) | ((uint32_t)p[1] << 16) |
                             ((uint32_t)p[2] << 8) | p[3]);
    M.flushed++;
    return 1;
}

/* ---- the real IKBD ----------------------------------------------------- */
#define R_ACIA_CR  0x00FFFC00u
#define R_ACIA_DR  0x00FFFC02u
static uint8_t  atx[256]; static unsigned atx_r, atx_w;     /* to the IKBD */
static void acia_send(uint8_t b) { if (atx_w - atx_r < sizeof atx) atx[atx_w++ & 255] = b; }

/* the guest changed the IKBD's mode: the real one follows, so its packets
 * carry what the guest expects (joystick 0 instead of the mouse, etc.) */
/* ---- the input log: every input change on its way to the guest -------
 * Written by the bus thread only (pad queue drain, real IKBD packets,
 * the guest's IKBD commands), printed by the reporter every 5 s. Kinds:
 * 'P' pad -> joystick (port, state), 'S' pad Start -> Space (down),
 * 'J' real IKBD joystick packet (port, state), 'K' real key (code),
 * 'C' guest IKBD command (byte), 'X' command forwarded to the real IKBD. */
#define ILOG 1024
typedef struct { uint32_t ms; char kind; uint8_t a, b; } ilog_t;
static ilog_t   ilog[ILOG];
static volatile unsigned ilog_w;
static uint64_t ilog_t0;
static void ilog_put(char kind, uint8_t a, uint8_t b)
{
    const unsigned w = ilog_w;
    ilog[w & (ILOG - 1)] = (ilog_t){ (uint32_t)((ticks() - ilog_t0) * NSPT / 1e6), kind, a, b };
    __atomic_thread_fence(__ATOMIC_RELEASE);
    ilog_w = w + 1;
}

static void m_ikbd(const uint8_t *c, int len)
{
    ilog_put('C', c[0], len > 1 ? c[1] : 0);
    switch (c[0]) {
    case 0x08: case 0x12: case 0x14: case 0x15: case 0x1A:
        ilog_put('X', c[0], 0);
        acia_send(c[0]); break;
    case 0x80:
        if (len >= 2 && c[1] == 0x01) { acia_send(0x80); acia_send(0x01); }
        break;
    default: break;
    }
}

/* hotkeys and disks */
static char    *g_disks[10];
static int      g_ndisks;
static int      g_kctrl, g_kalt, g_kshift;
static volatile int g_want_reset, g_want_quit, g_want_disk = -1;
static int g_relaunch;                      /* exit 42: run-pistorm.sh relaunches */

static void key_in(uint8_t code)
{
    const int down = !(code & 0x80);
    const uint8_t k = code & 0x7F;
    ilog_put('K', code, 0);
    if (k == 0x1D) g_kctrl = down;
    if (k == 0x38) g_kalt = down;
    if (k == 0x2A || k == 0x36) g_kshift = down;
    if (down && g_kctrl && g_kalt) {
        if (k == 0x61) { if (g_kshift) g_want_quit = 1; else g_want_reset = 1; return; }
        if (k >= 0x3B && k <= 0x44) { g_want_disk = k - 0x3B; return; }
        if (k == 0x62) { FC.req = 1; return; }                 /* Help: capture a frame */
    }
    stbox_key_event(k, down);
}

/* real IKBD bytes -> the box's input model */
static struct { uint8_t buf[8]; int n, need; } pk;
static void ikbd_byte(uint8_t b)
{
    M.acia_in++;
    if (pk.need) {
        pk.buf[pk.n++] = b;
        if (pk.n < pk.need) return;
        const uint8_t h = pk.buf[0];
        if (h >= 0xF8 && h <= 0xFB)           /* relative mouse          */
            stbox_mouse_rel((int8_t)pk.buf[1], (int8_t)pk.buf[2], h & 3);
        else if (h == 0xFE || h == 0xFF) {     /* joystick 0 / 1 event    */
            ilog_put('J', h - 0xFE, pk.buf[1]);
            stbox_joy_event(h - 0xFE, pk.buf[1]);
        } else if (h == 0xFD) {                /* joystick report         */
            ilog_put('J', 0, pk.buf[1]); ilog_put('J', 1, pk.buf[2]);
            stbox_joy_event(0, pk.buf[1]); stbox_joy_event(1, pk.buf[2]);
        }
        pk.need = pk.n = 0;
        return;
    }
    /* $00 is no key: outside a packet it is line noise, and passed on it
     * would be a key press the guest clicks for */
    if (b == 0x00) { M.acia_zero++; return; }
    int len = 0;
    if (b >= 0xF8 && b <= 0xFB) len = 3;
    else if (b == 0xFE || b == 0xFF) len = 2;
    else if (b == 0xFD) len = 3;
    else if (b == 0xF6) len = 8;
    else if (b == 0xF7) len = 6;
    else if (b == 0xFC) len = 7;
    else if (b == 0xF0 || b == 0xF1) return;   /* reset reply             */
    if (len) { pk.buf[0] = b; pk.n = 1; pk.need = len; return; }
    key_in(b);
}

static void acia_poll(void)
{
    const uint8_t sr = ps_read_8(R_ACIA_CR);
    if (sr & 0x20) M.acia_ovr++;
    if (sr & 0x01) {
        const uint8_t b = ps_read_8(R_ACIA_DR);
        /* a framing error is no byte the IKBD sent: a line held low (a
         * keyboard unplugged, or its 6301 held in reset) reads as a
         * stream of $00s, each with FE set, at the full 7812 baud */
        if (sr & 0x10) { M.acia_fe++; pk.need = pk.n = 0; }
        else ikbd_byte(b);
    }
    else if ((sr & 0x02) && atx_r != atx_w) { ps_write_8(R_ACIA_DR, atx[atx_r++ & 255]); M.acia_out++; }
}

static void acia_init(void)
{
    ps_write_8(R_ACIA_CR, 0x03);               /* master reset            */
    ps_write_8(R_ACIA_CR, 0x16);               /* /64, 8N1, no IRQs       */
    for (int i = 0; i < 4; i++) (void)ps_read_8(R_ACIA_DR);
    atx_r = atx_w = 0;
    acia_send(0x80); acia_send(0x01);          /* IKBD reset: mouse + joy */
}

static void ym_silence(void)
{
    static const uint8_t r[][2] = { { 7, 0x3F }, { 8, 0 }, { 9, 0 }, { 10, 0 } };
    for (unsigned i = 0; i < sizeof r / sizeof r[0]; i++) {
        ps_write_8(0x00FF8800u, r[i][0]);
        ps_write_8(0x00FF8802u, r[i][1]);
    }
}

/* what the bus thread did last, and for how long: a late write is put
 * down to it (0 waiting, 1 box slice, 2 RAM copy, 3 ACIA, 4 counter
 * read, 5 the write before) */
static int    g_act;
static double g_act_ns;
static const char *act_name[6] = { "nothing", "box slice", "RAM copy", "IKBD poll", "counter read", "previous write" };
static inline void act(int a, uint64_t t0)
{
    g_act = a;
    g_act_ns = (double)(ticks() - t0) * NSPT;
}

/* ---- USB / Bluetooth gamepads (joy_usb.c, as the emulator's) ----------
 * A thread on core 1 reads the pads through evdev; joy_usb.c maps them
 * (pad 0 = joystick 1, the game port; pad 1 = joystick 0; Start = Space).
 * The box's input ring has one producer - the bus thread - so the pad
 * thread posts here and the bus thread passes it on. */
#define PADQ 256
static volatile uint32_t padq[PADQ];
static volatile unsigned padq_w, padq_r;
static void padq_put(uint32_t v)
{
    unsigned w = padq_w;
    if (w - padq_r >= PADQ) return;
    padq[w & (PADQ - 1)] = v;
    __atomic_thread_fence(__ATOMIC_RELEASE);
    padq_w = w + 1;
}
static int  pad_send_joy(int st_port, uint8_t state, uint8_t pad_buttons)
{
    (void)pad_buttons;
    padq_put(0x01000000u | ((uint32_t)st_port << 8) | state);
    return 1;
}
static void pad_send_key(uint8_t sc, int down) { padq_put(0x02000000u | ((uint32_t)(down != 0) << 8) | sc); }
static int  pad_standalone(void) { return 0; }
static void padq_drain(void)                   /* bus thread */
{
    while (padq_r != padq_w) {
        __atomic_thread_fence(__ATOMIC_ACQUIRE);
        const uint32_t v = padq[padq_r & (PADQ - 1)];
        padq_r++;
        const unsigned kind = v >> 24;
        if (kind == 1)      { ilog_put('P', (v >> 8) & 1, (uint8_t)v); stbox_joy_event((v >> 8) & 1, (uint8_t)v); }
        else if (kind == 3) key_in((uint8_t)v);           /* USB/BT keyboard: as the real one, hotkeys too */
        else if (kind == 4) { ilog_put('M', (uint8_t)v, (uint8_t)(v >> 8));
                              stbox_mouse_rel((int8_t)(v & 0xFF), (int8_t)((v >> 8) & 0xFF), (v >> 16) & 3); }
        else                { ilog_put('S', (uint8_t)v, (v >> 8) & 1); stbox_key_event((uint8_t)v, (v >> 8) & 1); }
    }
}

static volatile int g_pad_stop;
static int g_pads;                          /* gamepads wanted (psctrl.cfg `usb`), below */
static void *pad_thread(void *arg)
{
    (void)arg;
    cpu_set_t cs; CPU_ZERO(&cs); CPU_SET(1, &cs);
    sched_setaffinity(0, sizeof cs, &cs);
    static const joy_usb_emit_hooks h = {
        .send_joy = pad_send_joy, .send_key = pad_send_key, .standalone = pad_standalone,
    };
    JOY_USB_enabled = true;
    joy_usb_set_hooks(&h);
    /* kind: 1 gamepad (joy_usb), 2 keyboard, 4 mouse - a combo receiver
     * can be keyboard and mouse at once */
    struct { int fd, pad, kind; char node[32]; } dev[16];
    int mdx = 0, mdy = 0, mbut = 0, msent = 0, mdirty = 0;
    int nd = 0;
    uint64_t next_scan = 0;
    while (!g_pad_stop) {
        struct timespec ts; clock_gettime(CLOCK_MONOTONIC, &ts);
        const uint64_t now = (uint64_t)ts.tv_sec * 1000u + (uint64_t)ts.tv_nsec / 1000000u;
        if (now >= next_scan) {                 /* hotplug: look once a second */
            next_scan = now + 1000;
            DIR *d = opendir("/dev/input");
            struct dirent *de;
            while (d && (de = readdir(d)) && nd < 16) {
                if (strncmp(de->d_name, "event", 5)) continue;
                char path[32];
                snprintf(path, sizeof path, "/dev/input/%.20s", de->d_name);
                int have = 0;
                for (int i = 0; i < nd; i++) if (!strcmp(dev[i].node, path)) have = 1;
                if (have) continue;
                int fd = open(path, O_RDONLY | O_NONBLOCK);
                if (fd < 0) continue;
                unsigned long ev[(EV_MAX / (8 * sizeof(long))) + 1] = {0};
                unsigned long key[(KEY_MAX / (8 * sizeof(long))) + 1] = {0};
                unsigned long ab[(ABS_MAX / (8 * sizeof(long))) + 1] = {0};
                ioctl(fd, EVIOCGBIT(0, sizeof ev), ev);
                ioctl(fd, EVIOCGBIT(EV_KEY, sizeof key), key);
                ioctl(fd, EVIOCGBIT(EV_ABS, sizeof ab), ab);
                unsigned long rl[(REL_MAX / (8 * sizeof(long))) + 1] = {0};
                ioctl(fd, EVIOCGBIT(EV_REL, sizeof rl), rl);
#define HASB(a, b) (((a)[(b) / (8 * sizeof(long))] >> ((b) % (8 * sizeof(long)))) & 1)
                int pad = -1, kind = 0;
                char name[64] = "?";
                ioctl(fd, EVIOCGNAME(sizeof name), name);
                if (joy_usb_is_gamepad(ev, key, ab)) {
                    if (g_pads) pad = joy_usb_dev_open(fd, name);
                    if (pad >= 0) kind = 1;
                } else {
                    if (HASB(ev, EV_KEY) && HASB(key, KEY_A) && HASB(key, KEY_SPACE) && HASB(key, KEY_ENTER)) kind |= 2;
                    if (HASB(ev, EV_REL) && HASB(rl, REL_X) && HASB(rl, REL_Y) && HASB(key, BTN_LEFT)) kind |= 4;
                }
#undef HASB
                if (!kind) { close(fd); continue; }
                if (kind == 1)
                    printf("[METAL] gamepad %d: %s (%s) = ST joystick %d\n", pad, name, path, pad == 0 ? 1 : 0);
                else {
                    /* keys and motion go to the ST only, not the Pi's console */
                    ioctl(fd, EVIOCGRAB, (void *)1L);
                    printf("[METAL] %s%s%s: %s (%s)\n", kind & 2 ? "keyboard" : "", kind == 6 ? " + " : "",
                           kind & 4 ? "mouse" : "", name, path);
                }
                dev[nd].fd = fd; dev[nd].pad = pad; dev[nd].kind = kind;
                snprintf(dev[nd].node, sizeof dev[nd].node, "%s", path);
                nd++;
            }
            if (d) closedir(d);
        }
        struct pollfd pf[16];
        for (int i = 0; i < nd; i++) { pf[i].fd = dev[i].fd; pf[i].events = POLLIN; }
        poll(pf, (nfds_t)nd, 10);
        for (int i = 0; i < nd; i++) {
            struct input_event e;
            for (;;) {
                ssize_t r = read(dev[i].fd, &e, sizeof e);
                if (r == (ssize_t)sizeof e) {
                    if (dev[i].kind == 1) { joy_usb_handle_event(dev[i].pad, &e); continue; }
                    if (e.type == EV_KEY && e.value != 2) {           /* 2 = autorepeat: the ST repeats itself */
                        const int down = e.value != 0;
                        if (e.code == BTN_LEFT)  { mbut = down ? (mbut | 2) : (mbut & ~2); mdirty = 1; }
                        else if (e.code == BTN_RIGHT) { mbut = down ? (mbut | 1) : (mbut & ~1); mdirty = 1; }
                        else if (e.code <= KEY_MAX && st_scan[e.code] != ST_NONE)
                            padq_put(0x03000000u | (down ? 0 : 0x80) | st_scan[e.code]);
                    } else if (e.type == EV_REL) {
                        if (e.code == REL_X) { mdx += e.value; mdirty = 1; }
                        else if (e.code == REL_Y) { mdy += e.value; mdirty = 1; }
                    } else if (e.type == EV_SYN && mdirty) {
                        /* one IKBD packet moves at most 127 each way */
                        do {
                            const int sx = mdx > 127 ? 127 : mdx < -127 ? -127 : mdx;
                            const int sy = mdy > 127 ? 127 : mdy < -127 ? -127 : mdy;
                            if (!sx && !sy && mbut == msent) break;
                            padq_put(0x04000000u | ((uint32_t)mbut << 16) | ((uint32_t)(uint8_t)sy << 8) | (uint8_t)sx);
                            mdx -= sx; mdy -= sy; msent = mbut;
                        } while (mdx || mdy);
                        mdirty = 0;
                    }
                    continue;
                }
                if (r < 0 && errno == EAGAIN) break;
                if (dev[i].kind == 1) {
                    printf("[METAL] gamepad %d gone\n", dev[i].pad);
                    joy_usb_dev_close(dev[i].pad);
                } else
                    printf("[METAL] %s gone (%s)\n", dev[i].kind & 2 ? "keyboard" : "mouse", dev[i].node);
                close(dev[i].fd);
                dev[i] = dev[--nd];
                i--;
                break;
            }
        }
        joy_usb_tick();
    }
    return NULL;
}

/* ---- the reporter (core 0: printf stays off the bus core) ------------- */
/* A double bus fault: everything needed to find out why, in one go -
 * the fault addresses, the head of the exception burst that led to it
 * (registers, stack, the 512 instructions before its first exception),
 * the instructions before the halt, and the whole of the box's RAM in
 * stboxmetal-halt-N.ram (raw, $000000 up) beside the log. */
static int g_ide_on, g_acsi_on;               /* hard disks, below */
void ide_dump_stats(void);                     /* IDE.c */
static void m_dis(uint32_t pc)
{
    char buf[128];
    pc &= 0xFFFFFF;
    m68k_disassemble(buf, pc, M68K_CPU_TYPE_68000);
    printf("[HALT]     %06X  %s\n", pc, buf);
}
static void m_pcs(const uint32_t *pcs, int n)
{
    /* runs of a loop collapse: an address seen in the last 16 is not repeated */
    int skipped = 0;
    for (int i = 0; i < n; i++) {
        int dup = 0;
        for (int j = i - 1; j >= 0 && j >= i - 16; j--) if (pcs[j] == pcs[i]) { dup = 1; break; }
        if (dup) { skipped++; continue; }
        if (skipped) { printf("[HALT]       (%d repeats of the lines above)\n", skipped); skipped = 0; }
        m_dis(pcs[i]);
    }
    if (skipped) printf("[HALT]       (%d repeats of the lines above)\n", skipped);
}
static void m_exc(const char *tag, const stbox_exc_info_t *e)
{
    printf("[HALT]   %s vec%u at pc %06X (next %06X) sr %04X sp %06X d0 %08X a0 %06X a1 %06X a6 %06X cyc %llu",
           tag, e->vector, e->ppc, e->pc, e->sr, e->sp, e->d0, e->a0, e->a1, e->a6,
           (unsigned long long)e->cycles);
    if (e->vector == 2) printf(" fault $%06X", e->addr);
    printf("\n[HALT]     stack:");
    for (int i = 0; i < 8; i++) printf(" %08X", e->stack[i]);
    printf("\n");
}
static void m_halt_report(void)
{
    static int nh;
    const stbox_halt_info_t *h = &stbox_halt_info;
    printf("[HALT] guest HALTED (double bus fault) at pc %06X (next %06X), sr %04X, sp %06X:"
           " first fault $%06X, second $%06X\n", h->ppc, h->pc, h->sr, h->sp, h->fault1, h->fault2);
    printf("[HALT] exceptions taken %u; the burst that led here started at exception %u:\n",
           stbox_exc_count, stbox_exc_head_at);
    printf("[HALT]   the %d instructions before its first exception (oldest first):\n", STBOX_HEAD_PCS);
    m_pcs(stbox_exc_head_pcs, STBOX_HEAD_PCS);
    for (unsigned i = 0; i < stbox_exc_head_n; i++) m_exc("burst", &stbox_exc_head[i]);
    printf("[HALT]   the last exceptions:\n");
    for (int i = STBOX_EXC_RING; i > 0; i--)
        if (stbox_exc_count >= (unsigned)i)
            m_exc("last", &stbox_exc_ring[(stbox_exc_count - i) & (STBOX_EXC_RING - 1)]);
    printf("[HALT]   the 256 instructions before the halt:\n");
    {
        static uint32_t last[256];
        const unsigned idx = stbox_pc_ring_idx;
        for (int i = 0; i < 256; i++) last[i] = stbox_pc_ring[(idx - 256 + i) & (STBOX_PC_RING - 1)];
        m_pcs(last, 256);
    }
    if (g_ide_on) { fflush(stdout); ide_dump_stats(); }
    char fn[64];
    snprintf(fn, sizeof fn, "stboxmetal-halt-%d.ram", ++nh);
    FILE *f = fopen(fn, "wb");
    if (f) { fwrite(stbox_shared.ram, 1, g_ram_bytes, f); fclose(f); }
    printf("[HALT] RAM ($000000-$%06X) written to %s%s\n", g_ram_bytes - 1, fn, f ? "" : " - FAILED");
    printf("[METAL] guest HALTED (double bus fault) at pc %06X: Ctrl+Alt+Undo to restart\n", h->ppc);
}

/* the frame capture, written out by the reporter thread */
#include "stbox_render.h"
static const char *m_reg(uint32_t a)
{
    static char b[16];
    if (a >= 0xFF8240 && a < 0xFF8260) { snprintf(b, sizeof b, "col%u", (a - 0xFF8240) / 2); return b; }
    switch (a) {
        case 0xFF820A: return "sync";  case 0xFF8260: return "rez";
        case 0xFF8201: return "vbhi";  case 0xFF8203: return "vbmid";
        case 0xFF8800: return "ymsel"; case 0xFF8802: return "ymdat";
    }
    snprintf(b, sizeof b, "%06X", a);
    return b;
}
static unsigned ilog_seen;
static void ilog_r_skip(void) { ilog_seen = ilog_w; }
static void ilog_print(void)
{
    unsigned seen = ilog_seen;
    const unsigned n = ilog_w;
    if (n == seen) return;
    if (n - seen > ILOG) seen = n - ILOG;
    char line[600]; int L = 0;
    for (; seen != n; seen++) {
        const ilog_t e = ilog[seen & (ILOG - 1)];
        char it[40];
        switch (e.kind) {
        case 'P': snprintf(it, sizeof it, " %u.%03u pad>j%u=%02X", e.ms / 1000, e.ms % 1000, e.a, e.b); break;
        case 'S': snprintf(it, sizeof it, " %u.%03u start>space%s", e.ms / 1000, e.ms % 1000, e.b ? "dn" : "up"); break;
        case 'J': snprintf(it, sizeof it, " %u.%03u ikbd>j%u=%02X", e.ms / 1000, e.ms % 1000, e.a, e.b); break;
        case 'K': snprintf(it, sizeof it, " %u.%03u key%02X", e.ms / 1000, e.ms % 1000, e.a); break;
        case 'M': snprintf(it, sizeof it, " %u.%03u mouse%+d,%+d", e.ms / 1000, e.ms % 1000, (int8_t)e.a, (int8_t)e.b); break;
        case 'C': snprintf(it, sizeof it, " %u.%03u guest-cmd%02X", e.ms / 1000, e.ms % 1000, e.a); break;
        default:  snprintf(it, sizeof it, " %u.%03u to-ikbd%02X", e.ms / 1000, e.ms % 1000, e.a); break;
        }
        const int il = (int)strlen(it);
        if (L + il > 160) { printf("[INPUT]%s\n", line); L = 0; }
        memcpy(line + L, it, (size_t)il + 1); L += il;
    }
    if (L) printf("[INPUT]%s\n", line);
    ilog_seen = seen;
}
static void input_state(const char *tag)
{
    uint32_t o[14];
    stbox_input_snapshot(o);
    printf("%s box IKBD: joy0 %02X joy1 %02X (last sent %02X %02X), joystick events %s, mouse %s%s,"
           " fifo %u, fifo drops %u, ring drops %u, packets %u/%u, ACIA rx irq %s, fire-as-RMB %u\n",
           tag, o[0], o[1], o[2], o[3], o[4] ? "on" : "off",
           o[5] == 0 ? "rel" : o[5] == 1 ? "abs" : o[5] == 2 ? "keys" : "off", o[6] ? " (both)" : "",
           o[7], o[8], o[9], o[10], o[11], (o[12] & 0x80) ? "on" : "off", o[13]);
    for (int i = 0; i < 2; i++) {
        char b[256];
        joy_usb_describe(i, b, sizeof b);
        printf("%s %s\n", tag, b);
    }
}

static void fc_report(void)
{
    FC.n++;
    unsigned stale_lines = 0, stale_longs = 0, late = 0;
    for (unsigned i = 0; i < FC.nl; i++) if (FC.l[i].stale > 0) { stale_lines++; stale_longs += FC.l[i].stale; }
    for (unsigned i = 0; i < FC.nw; i++) if (FC.w[i].late_ns > 1000) late++;
    {
        char tag[24]; snprintf(tag, sizeof tag, "[FRAME %d]", FC.n);
        input_state(tag);
    }
    printf("[FRAME %d] box frame %u: %u displayed lines, %u of them showed RAM not yet copied (%u longs);"
           " %u timed writes, %u over 1 us late\n", FC.n, FC.frame, FC.nl, stale_lines, stale_longs, FC.nw, late);
    printf("[FRAME %d] line bytes vcnt   stale | writes on the line: cycle reg=value +late_ns (b = in a burst) @pc\n", FC.n);
    unsigned wi = 0;
    for (unsigned i = 0; i < FC.nl || wi < FC.nw; ) {
        /* writes before this line (borders, lines without DE) get their own rows */
        const unsigned ln = i < FC.nl ? FC.l[i].line : 9999;
        if (wi < FC.nw && FC.w[wi].line < ln) {
            const unsigned wl = FC.w[wi].line;
            printf("[FRAME %d] %4u      -        - |", FC.n, wl);
            for (; wi < FC.nw && FC.w[wi].line == wl; wi++)
                printf(" %d %s=%X +%d%s @%06X", FC.w[wi].lcyc, m_reg(FC.w[wi].a), FC.w[wi].v, FC.w[wi].late_ns,
                       FC.w[wi].burst ? "b" : "", FC.w[wi].pc);
            printf("\n");
            continue;
        }
        if (i >= FC.nl) break;
        const cl_t *c = &FC.l[i++];
        printf("[FRAME %d] %4u %5u %06X %5d |", FC.n, c->line, c->bytes, c->vcnt, c->stale);
        for (; wi < FC.nw && FC.w[wi].line == c->line; wi++)
            printf(" %d %s=%X +%d%s @%06X", FC.w[wi].lcyc, m_reg(FC.w[wi].a), FC.w[wi].v, FC.w[wi].late_ns,
                   FC.w[wi].burst ? "b" : "", FC.w[wi].pc);
        printf("\n");
    }
    if (FC.have_pic) {
        static uint32_t px[1024 * 512];
        int w = 0, h = 0;
        stbox_render_set_view(24, 384);              /* borders too */
        if (stbox_render_cap(&FC.pic, 0, px, 1024, &w, &h)) {
            char fn[64];
            snprintf(fn, sizeof fn, "stboxmetal-frame-%d.ppm", FC.n);
            FILE *f = fopen(fn, "wb");
            if (f) {
                fprintf(f, "P6\n%d %d\n255\n", w, h);
                for (int y = 0; y < h; y++)
                    for (int x = 0; x < w; x++) {
                        const uint32_t v = px[(size_t)y * 1024 + x];
                        fputc((v >> 16) & 255, f); fputc((v >> 8) & 255, f); fputc(v & 255, f);
                    }
                fclose(f);
            }
            printf("[FRAME %d] the box's own picture of it (%dx%d, row 0 = line %u): %s%s\n", FC.n, w, h,
                   FC.pic.first_line, fn, f ? "" : " - FAILED");
        }
    }
    FC.state = 0;
}

static volatile int g_report_stop;
static void *reporter(void *arg)
{
    (void)arg;
    cpu_set_t cs; CPU_ZERO(&cs); CPU_SET(0, &cs);
    sched_setaffinity(0, sizeof cs, &cs);
    uint64_t lw = 0, lf = 0, lfr = 0;
    for (int sec = 5; !g_report_stop; sec += 5) {
        for (int i = 0; i < 50 && !g_report_stop; i++) {
            usleep(100000);
            if (FC.state == 5) fc_report();
        }
        if (!g_log) {                     /* quiet: only what needs attention */
            static uint64_t q_rel, q_drop, q_ovr, q_fe, q_zero;
            if (stbox_core_take_halt_report()) m_halt_report();
            char why[200]; int L = 0;
            if (M.relocks != q_rel)
                L += snprintf(why + L, sizeof why - L, " lost the beam and re-locked (%llu so far);",
                              (unsigned long long)M.relocks);
            if (M.q_drop != q_drop)
                L += snprintf(why + L, sizeof why - L, " %llu timed writes dropped (queue full);",
                              (unsigned long long)(M.q_drop - q_drop));
            /* a dead line (framing errors) overruns now and then too:
             * that is noise from the unplugged keyboard, not a lost key */
            if (M.acia_ovr != q_ovr && !(M.acia_fe - q_fe > 100 || M.acia_zero - q_zero > 100))
                L += snprintf(why + L, sizeof why - L, " %llu keyboard bytes lost (ACIA overrun);",
                              (unsigned long long)(M.acia_ovr - q_ovr));
            {   /* said once when it starts and once when it stops: an ST whose
                 * keyboard is unplugged would otherwise say it every 5 s */
                static int dead;
                const int now_dead = M.acia_fe - q_fe > 100 || M.acia_zero - q_zero > 100;
                if (now_dead && !dead)
                    L += snprintf(why + L, sizeof why - L, " the ST keyboard line is dead (%llu framing errors in 5 s) -"
                                  " keyboard unplugged? Its bytes are ignored; USB/Bluetooth keyboards still work;",
                                  (unsigned long long)(M.acia_fe - q_fe));
                else if (!now_dead && dead)
                    L += snprintf(why + L, sizeof why - L, " the ST keyboard line is alive again;");
                else if (!now_dead && (M.acia_fe != q_fe || M.acia_zero != q_zero))
                    L += snprintf(why + L, sizeof why - L, " %llu bad keyboard bytes dropped;",
                                  (unsigned long long)(M.acia_fe - q_fe + M.acia_zero - q_zero));
                dead = now_dead;
            }
            q_fe = M.acia_fe; q_zero = M.acia_zero;
            if (L) printf("[METAL] %dm%02ds:%s\n", sec / 60, sec % 60, why);
            q_rel = M.relocks; q_drop = M.q_drop; q_ovr = M.acia_ovr;
            /* keep the per-interval maxima from growing without bound */
            M.late_max_ns = 0; M.slice_max_ns = 0; M.q_max = 0; M.e_max = 0; M.burst_late_max_ns = 0;
            M.box_ns = M.flush_ns = M.wait_ns = 0; M.box_behind = 0;
            M.flush_max_ns = M.poll_max_ns = M.probe_max_ns = 0;
            vc_r = vc_w;
            ilog_r_skip();
            continue;
        }
        ilog_print();
        const double n = M.probe_ok ? (double)M.probe_ok : 1.0;
        const double em = M.e_sum / n, sd = sqrt(fmax(0.0, M.e_sq / n - em * em));
        printf("[METAL] %3ds frames %u (+%llu) cps %u | writes +%llu (in bursts %llu, max %.0f ns late) others late>1us %llu max %.0f ns, queue max %llu drop %llu"
               " | RAM longs +%llu | lock reads ok %llu rejected %llu late %llu skipped %llu, err sd %.2f max %.1f cyc, relocks %llu"
               " | box %.0f %% (slice max %.0f ns, behind %llu), RAM copy %.0f %%, waiting %.0f %% | IKBD in %llu out %llu ovr %llu fe %llu zero %llu\n",
               sec, stbox_shared.frame, (unsigned long long)(stbox_shared.frame - lfr), stbox_core_cps(),
               (unsigned long long)(M.writes - lw), (unsigned long long)M.burst, M.burst_late_max_ns,
               (unsigned long long)M.late1us, M.late_max_ns,
               (unsigned long long)M.q_max, (unsigned long long)M.q_drop,
               (unsigned long long)(M.flushed - lf),
               (unsigned long long)M.probe_ok, (unsigned long long)M.probe_rej,
               (unsigned long long)M.probe_late, (unsigned long long)M.probe_skip,
               sd, M.e_max, (unsigned long long)M.relocks,
               M.box_ns / 5e7, M.slice_max_ns, (unsigned long long)M.box_behind,
               M.flush_ns / 5e7, M.wait_ns / 5e7,
               (unsigned long long)M.acia_in, (unsigned long long)M.acia_out, (unsigned long long)M.acia_ovr,
               (unsigned long long)M.acia_fe, (unsigned long long)M.acia_zero);
        if (M.late1us) {
            printf("[METAL]       late writes came after:");
            for (int i = 0; i < 6; i++)
                if (M.late_by[i]) printf(" %s %llu (longest %.0f ns)", act_name[i],
                                         (unsigned long long)M.late_by[i], M.late_by_ns[i]);
            printf(" | longest RAM copy %.0f ns, IKBD poll %.0f ns, counter read %.0f ns\n",
                   M.flush_max_ns, M.poll_max_ns, M.probe_max_ns);
            M.flush_max_ns = M.poll_max_ns = M.probe_max_ns = 0;
        }
        if (g_vmoved) printf("[METAL]       writes moved off the vertical decision: %llu\n", (unsigned long long)g_vmoved);
        if (stbox_core_take_halt_report()) m_halt_report();
        printf("[METAL]       top border: box shut %llu/%llu frames real agrees, box open %llu/%llu"
               " | bottom border (box open): %llu/%llu\n",
               (unsigned long long)M.top_ok[0], (unsigned long long)M.top_n[0],
               (unsigned long long)M.top_ok[1], (unsigned long long)M.top_n[1],
               (unsigned long long)M.bot_ok, (unsigned long long)M.bot_n);
        while (vc_r != vc_w) {
            __atomic_thread_fence(__ATOMIC_ACQUIRE);
            const vcase_t *c = &vc[vc_r & (VC - 1)];
            printf("[METAL]   frame %u: real ST differs at line %u (%s border, box %s, box's first displayed line %u):"
                   " real counter %+d bytes into the line, box says %+d\n",
                   c->frame, c->line, c->tag == V_TOP ? "top" : "bottom",
                   (c->tag == V_BOT || c->box_open) ? "open" : "shut", c->first, c->real_off, c->model_off);
            printf("[METAL]     writes:");
            for (int i = 0; i < c->nw; i++)
                printf(" L%d c%d %s=%02X (+%dns)", c->w[i].line, c->w[i].cyc,
                       c->w[i].a == 0x0A ? "sync" : "rez", c->w[i].v, c->w[i].late10 * 10);
            if (!c->nw) printf(" none");
            printf("\n");
            vc_r++;
        }
        lw = M.writes; lf = M.flushed; lfr = stbox_shared.frame;
        M.late_max_ns = 0; M.slice_max_ns = 0; M.q_max = 0; M.e_max = 0; M.burst_late_max_ns = 0;
        M.box_ns = M.flush_ns = M.wait_ns = 0; M.box_behind = 0;
        if (stbox_exc_count) {
            static unsigned seen;
            const unsigned n = stbox_exc_count;
            if (n - seen > STBOX_EXC_RING) {
                printf("[METAL] guest exceptions: %u in 5 s, the last %d:\n", n - seen, STBOX_EXC_RING);
                seen = n - STBOX_EXC_RING;
            }
            for (; seen != n; seen++) {
                stbox_exc_info_t e = stbox_exc_ring[seen & (STBOX_EXC_RING - 1)];
                if (e.vector == 2)
                    printf("[METAL] guest exception vec2 (bus error at $%06X) at pc %06X (sr %04X)\n",
                           e.addr, e.ppc, e.sr);
                else
                    printf("[METAL] guest exception vec%u at pc %06X (sr %04X)\n", e.vector, e.ppc, e.sr);
            }
        }
    }
    return NULL;
}

