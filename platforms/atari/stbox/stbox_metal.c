/* SPDX-License-Identifier: MIT
 *
 * stbox_metal.c - STBOX on the metal: the sandbox ST (Musashi 68000 with
 * the box's own MFP, GLUE timing, ACIA, FDC) runs in the Pi, and drives
 * the REAL ST's chips: the real Shifter shows the picture on the ST's own
 * monitor, the real YM plays the sound, the real keyboard, mouse and
 * joysticks are the input.
 *
 * Why. With the CPU on the Pi and the chips on the far side of the
 * PiStorm bus, every bus read waits ~1 us and interrupts are seen up to
 * 15 us late, so every game needs its own timing fix. Here nothing the
 * guest does ever waits on the bus: the timing that matters (MFP timers,
 * Timer B, HBL/VBL, the video counter) is the box's own, exact and
 * deterministic, and the real chips only receive writes - each one
 * played onto the real bus at the cycle the box made it, against the
 * real beam. tools/beamtest proved that works: right-border writes land
 * in their 4-cycle bus slot on >99.99 % of lines (22 Nov 2026, Pi 4).
 *
 *   sudo systemctl stop pistorm
 *   make stboxmetal
 *   sudo ./stboxmetal --tos /home/pistorm/roms/tos104uk.rom \
 *        --disk "/home/pistorm/games-share/Xenon2.st" 2>&1 | tee stboxmetal.log
 *
 * Normally it is started by the setup page: a psctrl.cfg build with
 * `engine metal` (doc/PSCTRL-CFG.md) makes the emulator exec
 *   ./stboxmetal --config ../configs/psctrl.cfg --build <section>
 * which takes the build's rom, fastboot, IDE (hdd) and ACSI images and
 * floppies from the file.
 *
 * USB / Bluetooth gamepads (Xbox pads) work as in the emulator: the first
 * is joystick 1, the second joystick 0, Start is the Space bar.
 *
 * Keys (real keyboard): Ctrl+Alt+Undo = back to the setup page (exit 42,
 * run-pistorm.sh relaunches the emulator) when started from a build, a
 * cold reset of the box when started by hand; Ctrl+Alt+F1..F10 = put
 * disk 1..10 in drive A, Ctrl+Alt+Help = capture the next frame (its
 * writes, stale RAM per line, the box's own picture - into the log and
 * stboxmetal-frame-N.ppm), Ctrl+Alt+Shift+Undo = quit (so does Ctrl+C).
 *
 * HOW IT RUNS. One thread on an isolated core owns the bus and does
 * everything, in priority order:
 *   1. a timed write due within GUARD: wait for its moment, write it;
 *   2. the box behind the beam + AHEAD: run one box slice (<= 64 cycles);
 *   3. RAM the box wrote and the real Shifter may show: copy it over
 *      (dirty bitmap, the box's current screen first);
 *   4. the real ACIA: poll for IKBD bytes, send queued commands.
 * Box cycles map to Pi time linearly (mT0, mA0, TPC). The map starts from
 * beamtest's lock (a plain 50 Hz screen) at the box's cold reset, and is
 * kept by reading the real video counter once a frame on a displayed line
 * and comparing it with what the box's GLUE says the counter is there.
 *
 * WHAT GOES TO THE REAL ST. Guest writes to $FF8200-$FF82FF (video base,
 * sync, palette, resolution) and $FF8800-$FF88FF (YM), as the CPU made
 * them, at their cycle; RAM, through the dirty bitmap. Never: the MMU
 * ($FF8001 - the real one is set once from the real banks), the MFP, the
 * FDC/DMA, the ACIA (the box emulates them; the real IKBD is read here
 * and its keys, mouse and joysticks fed to the box's IKBD model, which
 * answers the guest in whatever mode the guest asked for).
 *
 * Hard disks: IDE at $F00000 and emulated ACSI targets, the emulator's
 * own IDE.c / acsi.c behind the box's address decode and DMA chip.
 *
 * Not yet: the real floppy drive (disk images only), HDMI, STE.
 */
