/* ---- the time map: box cycle -> Pi tick ------------------------------- */
static double   mT0;                        /* tick of box cycle mA0      */
static uint64_t mA0;
static int      g_ahead = 1024;             /* box runs this far ahead    */
static uint64_t g_synth;                    /* the box's clock: monotonic */
static inline double m_time(double abs) { return mT0 + (abs - (double)mA0) * TPC; }
static inline double m_abs(double t)    { return (double)mA0 + (t - mT0) / TPC; }

/* ---- stats (written by the bus thread, printed by the reporter) ------- */
static struct {
    uint64_t writes, late1us, burst, q_drop, q_max, box_slices, box_behind;
    double   burst_late_max_ns;
    uint64_t flushed, acia_in, acia_out, acia_ovr;
    uint64_t probes, probe_ok, probe_rej, probe_late, probe_skip;
    double   e_sum, e_sq, e_max, late_max_ns, slice_max_ns, box_ns, flush_ns, wait_ns;
    uint64_t relocks, resets;
} M;
#define M_INIT() memset(&M, 0, sizeof M)

/* ---- timed writes ------------------------------------------------------ */
typedef struct { uint64_t abs; uint32_t a; uint16_t v; uint8_t size, pad; } mev_t;
#define MQ (1u << 16)
static mev_t    mq[MQ];
static unsigned mq_r, mq_w;

static uint64_t g_last_abs;
static void m_hw(uint64_t abs, uint32_t a, uint32_t v, int size)
{
    /* writes are at least a bus cycle apart: Musashi stamps every write
     * of one instruction (movem to the palette) with the same cycle */
    if (abs < g_last_abs + 4 && g_last_abs - abs < 1024) abs = g_last_abs + 4;
    g_last_abs = abs;
    if (mq_w - mq_r >= MQ) { M.q_drop++; return; }
    mq[mq_w & (MQ - 1)] = (mev_t){ abs, a, (uint16_t)v, (uint8_t)size, 0 };
    mq_w++;
    if (mq_w - mq_r > M.q_max) M.q_max = mq_w - mq_r;
}

/* ---- lock tracking: one real counter read a frame ---------------------- */
typedef struct { uint64_t abs_line; unsigned line; int fstart; unsigned bytes; uint32_t vcnt; } mline_t;
static struct {
    int      pending;                       /* a read scheduled           */
    uint64_t abs;                           /* where                      */
    mline_t  ln;                            /* the line it is on          */
    uint64_t last_abs;                      /* last good read             */
    int      rej_run;
    uint32_t frame_seen;                    /* box frame of the last one  */
} P1;

static void m_line(uint64_t abs_line, unsigned line, int fstart, unsigned bytes, uint32_t vcnt)
{
    /* one read a box frame, mid-line on a plain-ish displayed line, where
     * no timed write is queued within 64 cycles of it */
    if (P1.pending || P1.frame_seen == stbox_shared.frame) return;
    if (bytes < 160 || fstart > 56 || line < 40) return;
    const uint64_t at = abs_line + (uint64_t)fstart + 64u + (uint64_t)(P1.frame_seen & 3);
    for (unsigned j = mq_w; j != mq_r; ) {
        j--;
        const mev_t *e = &mq[j & (MQ - 1)];
        if (e->abs + 64 < at) break;
        if (e->abs <= at + 64) { M.probe_skip++; return; }
    }
    P1.pending = 1;
    P1.abs = at;
    P1.ln = (mline_t){ abs_line, line, fstart, bytes, vcnt };
    P1.frame_seen = stbox_shared.frame;
}

static void m_probe(void)
{
    P1.pending = 0;
    M.probes++;
    uint32_t cnt; uint64_t t;
    const double due = m_time((double)P1.abs);
    if (!read_counter(&cnt, &t)) { M.probe_rej++; P1.rej_run++; return; }
    if (((double)t - due) * NSPT > 2000.0) { M.probe_late++; return; }
    const long off = (long)cnt - (long)P1.ln.vcnt;
    if (off <= 0 || off >= (long)P1.ln.bytes) { M.probe_rej++; P1.rej_run++; return; }
    const double abs_true = (double)P1.ln.abs_line + P1.ln.fstart + 2.0 * off + 2.0;
    const double e = m_abs((double)t) - abs_true;      /* + = map runs early */
    if (fabs(e) > 64.0) {
        M.probe_rej++;
        if (++P1.rej_run >= 8) {              /* trust the counter        */
            mT0 += e * TPC; P1.rej_run = 0; M.relocks++;
        }
        return;
    }
    P1.rej_run = 0;
    M.probe_ok++; M.e_sum += e; M.e_sq += e * e;
    if (fabs(e) > M.e_max) M.e_max = fabs(e);
    /* shifter_mirror.c's loop: phase a quarter (all beyond 8 cycles),
     * rate a sixteenth spread over the cycles since the last good read;
     * re-anchored at this read so a new rate moves nothing behind it */
    const double Tn = m_time(abs_true) + (fabs(e) > 8.0 ? e : e / 4.0) * TPC;
    if (P1.last_abs && abs_true > (double)P1.last_abs) {
        const double dc = abs_true - (double)P1.last_abs;
        if (dc < 4.0 * 160256.0) TPC += e * TPC / 16.0 / dc;
    }
    mA0 = (uint64_t)abs_true;
    mT0 = Tn - (abs_true - (double)mA0) * TPC;
    P1.last_abs = (uint64_t)abs_true;
}

/* ---- RAM: the box's writes, copied to the real ST-RAM ------------------ */
static uint64_t *g_dirty;
static uint8_t  *g_blk;
static uint32_t  g_ram_bytes;
static uint32_t  g_cur_scr, g_cur_all;       /* scan cursors              */

/* Next dirty long in [lo, hi): blocks in order from the one *cur is in,
 * wrapping, lowest address first inside a block. A block found with no
 * bit left is marked clean. -1 = nothing dirty in the range. */
static long dirty_next(uint32_t lo, uint32_t hi, uint32_t *cur)
{
    if (hi <= lo) return -1;
    const uint32_t blo = lo >> 14, bhi = (hi - 1) >> 14;
    uint32_t b = (*cur >= lo && *cur < hi) ? (*cur >> 14) : blo;
    for (uint32_t i = 0; i <= bhi - blo; i++) {
        if (g_blk[b]) {
            int any = 0;
            for (uint32_t w = b << 6; w < (b + 1) << 6; w++) {
                uint64_t m = g_dirty[w];
                if (!m) continue;
                any = 1;
                while (m) {
                    const uint32_t o = (w << 8) + 4u * (uint32_t)__builtin_ctzll(m);
                    if (o >= lo && o < hi) { *cur = o; return (long)o; }
                    m &= m - 1;
                }
            }
            if (!any) g_blk[b] = 0;
        }
        b = b == bhi ? blo : b + 1;
    }
    return -1;
}

static int flush_one(void)
{
    if (!stbox_metal_any) return 0;
    const uint32_t vb = stbox_shared.video_base & (g_ram_bytes - 1) & ~0xFFu;
    uint32_t hi = vb + 0x10000u; if (hi > g_ram_bytes) hi = g_ram_bytes;
    long o = dirty_next(vb, hi, &g_cur_scr);
    if (o < 0) o = dirty_next(0, g_ram_bytes, &g_cur_all);
    if (o < 0) { stbox_metal_any = 0; return 0; }
    g_dirty[o >> 8] &= ~(1ull << ((o >> 2) & 63));
    const uint8_t *p = stbox_shared.ram + o;
    ps_write_32((uint32_t)o, ((uint32_t)p[0] << 24) | ((uint32_t)p[1] << 16) |
                             ((uint32_t)p[2] << 8) | p[3]);
    M.flushed++;
    return 1;
}

/* ---- the real IKBD ----------------------------------------------------- */
#define R_ACIA_CR  0x00FFFC00u
#define R_ACIA_DR  0x00FFFC02u
static uint8_t  atx[256]; static unsigned atx_r, atx_w;     /* to the IKBD */
static void acia_send(uint8_t b) { if (atx_w - atx_r < sizeof atx) atx[atx_w++ & 255] = b; }

/* the guest changed the IKBD's mode: the real one follows, so its packets
 * carry what the guest expects (joystick 0 instead of the mouse, etc.) */
static void m_ikbd(const uint8_t *c, int len)
{
    switch (c[0]) {
    case 0x08: case 0x12: case 0x14: case 0x15: case 0x1A:
        acia_send(c[0]); break;
    case 0x80:
        if (len >= 2 && c[1] == 0x01) { acia_send(0x80); acia_send(0x01); }
        break;
    default: break;
    }
}

/* hotkeys and disks */
static char    *g_disks[10];
static int      g_ndisks;
static int      g_kctrl, g_kalt, g_kshift;
static volatile int g_want_reset, g_want_quit, g_want_disk = -1;

static void key_in(uint8_t code)
{
    const int down = !(code & 0x80);
    const uint8_t k = code & 0x7F;
    if (k == 0x1D) g_kctrl = down;
    if (k == 0x38) g_kalt = down;
    if (k == 0x2A || k == 0x36) g_kshift = down;
    if (down && g_kctrl && g_kalt) {
        if (k == 0x61) { if (g_kshift) g_want_quit = 1; else g_want_reset = 1; return; }
        if (k >= 0x3B && k <= 0x44) { g_want_disk = k - 0x3B; return; }
    }
    stbox_key_event(k, down);
}

/* real IKBD bytes -> the box's input model */
static struct { uint8_t buf[8]; int n, need; } pk;
static void ikbd_byte(uint8_t b)
{
    M.acia_in++;
    if (pk.need) {
        pk.buf[pk.n++] = b;
        if (pk.n < pk.need) return;
        const uint8_t h = pk.buf[0];
        if (h >= 0xF8 && h <= 0xFB)           /* relative mouse          */
            stbox_mouse_rel((int8_t)pk.buf[1], (int8_t)pk.buf[2], h & 3);
        else if (h == 0xFE || h == 0xFF)       /* joystick 0 / 1 event    */
            stbox_joy_event(h - 0xFE, pk.buf[1]);
        else if (h == 0xFD) {                  /* joystick report         */
            stbox_joy_event(0, pk.buf[1]); stbox_joy_event(1, pk.buf[2]);
        }
        pk.need = pk.n = 0;
        return;
    }
    int len = 0;
    if (b >= 0xF8 && b <= 0xFB) len = 3;
    else if (b == 0xFE || b == 0xFF) len = 2;
    else if (b == 0xFD) len = 3;
    else if (b == 0xF6) len = 8;
    else if (b == 0xF7) len = 6;
    else if (b == 0xFC) len = 7;
    else if (b == 0xF0 || b == 0xF1) return;   /* reset reply             */
    if (len) { pk.buf[0] = b; pk.n = 1; pk.need = len; return; }
    key_in(b);
}

static void acia_poll(void)
{
    const uint8_t sr = ps_read_8(R_ACIA_CR);
    if (sr & 0x20) M.acia_ovr++;
    if (sr & 0x01) ikbd_byte(ps_read_8(R_ACIA_DR));
    else if ((sr & 0x02) && atx_r != atx_w) { ps_write_8(R_ACIA_DR, atx[atx_r++ & 255]); M.acia_out++; }
}

static void acia_init(void)
{
    ps_write_8(R_ACIA_CR, 0x03);               /* master reset            */
    ps_write_8(R_ACIA_CR, 0x16);               /* /64, 8N1, no IRQs       */
    for (int i = 0; i < 4; i++) (void)ps_read_8(R_ACIA_DR);
    atx_r = atx_w = 0;
    acia_send(0x80); acia_send(0x01);          /* IKBD reset: mouse + joy */
}

static void ym_silence(void)
{
    static const uint8_t r[][2] = { { 7, 0x3F }, { 8, 0 }, { 9, 0 }, { 10, 0 } };
    for (unsigned i = 0; i < sizeof r / sizeof r[0]; i++) {
        ps_write_8(0x00FF8800u, r[i][0]);
        ps_write_8(0x00FF8802u, r[i][1]);
    }
}

/* ---- the reporter (core 0: printf stays off the bus core) ------------- */
static volatile int g_report_stop;
static void *reporter(void *arg)
{
    (void)arg;
    cpu_set_t cs; CPU_ZERO(&cs); CPU_SET(0, &cs);
    sched_setaffinity(0, sizeof cs, &cs);
    uint64_t lw = 0, lf = 0, lfr = 0;
    for (int sec = 5; !g_report_stop; sec += 5) {
        for (int i = 0; i < 50 && !g_report_stop; i++) usleep(100000);
        const double n = M.probe_ok ? (double)M.probe_ok : 1.0;
        const double em = M.e_sum / n, sd = sqrt(fmax(0.0, M.e_sq / n - em * em));
        printf("[METAL] %3ds frames %u (+%llu) cps %u | writes +%llu (in bursts %llu, max %.0f ns late) others late>1us %llu max %.0f ns, queue max %llu drop %llu"
               " | RAM longs +%llu | lock reads ok %llu rejected %llu late %llu skipped %llu, err sd %.2f max %.1f cyc, relocks %llu"
               " | box %.0f %% (slice max %.0f ns, behind %llu), RAM copy %.0f %%, waiting %.0f %% | IKBD in %llu out %llu ovr %llu\n",
               sec, stbox_shared.frame, (unsigned long long)(stbox_shared.frame - lfr), stbox_core_cps(),
               (unsigned long long)(M.writes - lw), (unsigned long long)M.burst, M.burst_late_max_ns,
               (unsigned long long)M.late1us, M.late_max_ns,
               (unsigned long long)M.q_max, (unsigned long long)M.q_drop,
               (unsigned long long)(M.flushed - lf),
               (unsigned long long)M.probe_ok, (unsigned long long)M.probe_rej,
               (unsigned long long)M.probe_late, (unsigned long long)M.probe_skip,
               sd, M.e_max, (unsigned long long)M.relocks,
               M.box_ns / 5e7, M.slice_max_ns, (unsigned long long)M.box_behind,
               M.flush_ns / 5e7, M.wait_ns / 5e7,
               (unsigned long long)M.acia_in, (unsigned long long)M.acia_out, (unsigned long long)M.acia_ovr);
        lw = M.writes; lf = M.flushed; lfr = stbox_shared.frame;
        M.late_max_ns = 0; M.slice_max_ns = 0; M.q_max = 0; M.e_max = 0; M.burst_late_max_ns = 0;
        M.box_ns = M.flush_ns = M.wait_ns = 0; M.box_behind = 0;
        if (stbox_exc_count) {
            static unsigned seen;
            for (; seen != stbox_exc_count; seen++) {
                stbox_exc_info_t e = stbox_exc_ring[seen & (STBOX_EXC_RING - 1)];
                if (e.vector != 2)
                    printf("[METAL] guest exception vec%u at pc %06X (sr %04X)\n", e.vector, e.ppc, e.sr);
            }
        }
    }
    return NULL;
}

/* ---- start / restart ---------------------------------------------------- */
/* (Re)lock to a plain screen and start the box from a cold reset with its
 * frame 0 on the next real frame. */
static int m_start_box(void)
{
    bt_plain_screen();
    ym_silence();
    usleep(60000);
    if (lock(1) != 0) return -1;
    mq_r = mq_w = 0;
    g_last_abs = 0;
    memset(&P1, 0, sizeof P1);
    P1.frame_seen = 0xFFFFFFFFu;
    long n = (long)floor(((double)ticks() - O) / P) + 2;
    mA0 = 0;
    mT0 = O + (double)n * P;                   /* box cycle 0 = that frame */
    stbox_request_reset();
    g_synth = 0;
    stbox_core_arm(0, ST_HZ);                  /* 1 synthetic tick = 1 cycle */
    return 0;
}

static void m_disk(int i)
{
    if (i < 0 || i >= g_ndisks) return;
    uint32_t sz = 0;
    uint8_t *img = disk_load(g_disks[i], &sz);
    if (!img) return;
    stbox_core_disarm();                        /* adopt synchronously     */
    uint8_t *old = stbox_core_disk_insert(img, sz);
    free(old);
    stbox_core_arm(g_synth, ST_HZ);
    printf("[METAL] drive A: %s\n", g_disks[i]);
}

int main(int argc, char **argv)
{
    const char *tos = "/home/pistorm/roms/tos104uk.rom";
    double cal_secs = 5.0;
    int core = 3;
    for (int i = 1; i < argc; i++) {
        if (!strcmp(argv[i], "--tos") && i + 1 < argc) tos = argv[++i];
        else if (!strcmp(argv[i], "--disk") && i + 1 < argc) { if (g_ndisks < 10) g_disks[g_ndisks++] = argv[++i]; else i++; }
        else if (!strcmp(argv[i], "--cal") && i + 1 < argc) { g_cal = atof(argv[++i]); cal_forced = 1; }
        else if (!strcmp(argv[i], "--cal-secs") && i + 1 < argc) cal_secs = atof(argv[++i]);
        else if (!strcmp(argv[i], "--ahead") && i + 1 < argc) g_ahead = atoi(argv[++i]);
        else if (!strcmp(argv[i], "--core") && i + 1 < argc) core = atoi(argv[++i]);
        else {
            fprintf(stderr, "usage: %s [--tos ROM] [--disk IMG]... [--cal CYCLES | --cal-secs S]"
                            " [--ahead CYCLES] [--core N]\n", argv[0]);
            return 2;
        }
    }
    setvbuf(stdout, NULL, _IOLBF, 0);

    /* ROM and RAM before the bus: a bad path costs nothing */
    static uint8_t rom[512 * 1024];
    FILE *f = fopen(tos, "rb");
    if (!f) { printf("%s: %s\n", tos, strerror(errno)); return 2; }
    size_t rsz = fread(rom, 1, sizeof rom, f);
    fclose(f);

    if (bt_init("stboxmetal", core)) return 1;
    g_ram_bytes = scr.bank0 + scr.bank1;
    if (g_ram_bytes != (512u << 10) && g_ram_bytes != (1024u << 10) &&
        g_ram_bytes != (2048u << 10) && g_ram_bytes != (4096u << 10)) {
        printf("ST-RAM %u K is not a size the box models (512 K, 1, 2, 4 MB)\n", g_ram_bytes >> 10);
        return 1;
    }
    uint8_t *ram = calloc(1, g_ram_bytes + 32768);
    g_dirty = calloc(g_ram_bytes / 256, sizeof *g_dirty);
    g_blk = calloc(g_ram_bytes / 16384 + 1, 1);
    if (!ram || !g_dirty || !g_blk) { printf("out of memory\n"); return 1; }
    stbox_shared.ram = ram; stbox_shared.ram_size = g_ram_bytes;
    stbox_core_set_machine(0);
    if (stbox_core_setup(ram, g_ram_bytes, rom, (uint32_t)rsz)) { printf("box setup failed (ROM?)\n"); return 1; }
    if (g_ndisks) {
        uint32_t sz = 0;
        uint8_t *img = disk_load(g_disks[0], &sz);
        if (img) { stbox_core_disk_insert(img, sz); printf("drive A: %s\n", g_disks[0]); }
    }
    printf("box: TOS %s, %u K\n", tos, g_ram_bytes >> 10);

    /* calibrate the write landing, as beamtest's B */
    printf("\n[A] LOCK\n");
    if (lock(0) != 0) return 1;
    measure_writes();
    if (!cal_forced) {
        printf("\n[B] RIGHT BORDER SWEEP (calibration, %.0f s)\n", cal_secs);
        run_phase(PH_RIGHT, cal_secs);
        report_common();
        report_sweep(1);
        bt_calibrate_from_sweep(cal_secs);
    } else
        printf("calibration %+.2f cycles (--cal)\n", g_cal);

    /* hand the machine to the box */
    M_INIT();
    stbox_metal_hw = m_hw;
    stbox_metal_line = m_line;
    stbox_metal_ikbd = m_ikbd;
    stbox_metal_dirty = g_dirty;
    stbox_metal_blk = g_blk;
    acia_init();
    if (m_start_box() != 0) return 1;
    printf("\n[METAL] running: Ctrl+Alt+Undo reset, Ctrl+Alt+F1..F%d disks, Ctrl+Alt+Shift+Undo quit\n",
           g_ndisks ? g_ndisks : 1);
    pthread_t rep;
    pthread_create(&rep, NULL, reporter, NULL);

    const double guard = GUARD_NS / NSPT, boxrun = BOXRUN_NS / NSPT,
                 flushg = FLUSH_NS / NSPT, pollg = POLL_NS / NSPT;
    const uint64_t poll_every = (uint64_t)(ACIA_POLL_US * 1000.0 / NSPT);
    uint64_t next_poll = ticks();

    while (!g_stop && !g_want_quit) {
        if (g_want_reset) {
            g_want_reset = 0; M.resets++;
            printf("[METAL] cold reset\n");
            stbox_core_disarm();
            if (m_start_box() != 0) break;
            continue;
        }
        if (g_want_disk >= 0) { int d = g_want_disk; g_want_disk = -1; m_disk(d); continue; }

        const double now = (double)ticks();
        /* the next timed thing: a queued write or the lock read */
        double tn = 1e30; int is_probe = 0;
        if (mq_r != mq_w) {
            const mev_t *e = &mq[mq_r & (MQ - 1)];
            tn = m_time((double)e->abs + g_cal) - (e->size == 1 ? LEAD8 : LEAD16);
        }
        if (P1.pending) {
            const double tp = m_time((double)P1.abs);
            if (tp < tn) { tn = tp; is_probe = 1; }
        }
        const double gap = tn - now;

        if (gap < guard) {
            const uint64_t w0 = ticks();
            while ((double)ticks() < tn) ;
            M.wait_ns += (double)(ticks() - w0) * NSPT;
            if (is_probe) { m_probe(); continue; }
            const mev_t *e = &mq[mq_r & (MQ - 1)];
            const uint64_t t0 = ticks();
            if (e->size == 1) ps_write_8(e->a, e->v);
            else              ps_write_16(e->a, e->v);
            const double late = ((double)t0 - tn) * NSPT;
            /* a write within 16 cycles of the one before is a burst (movem
             * to the palette): our bus write is ~0.7 us against the
             * 68000's 0.5, so a burst falls behind by design. The lateness
             * that matters for raster tricks is that of the others. */
            static uint64_t prev_abs;
            if (e->abs - prev_abs < 16) {
                M.burst++;
                if (late > M.burst_late_max_ns) M.burst_late_max_ns = late;
            } else {
                if (late > 1000.0) M.late1us++;
                if (late > M.late_max_ns) M.late_max_ns = late;
            }
            prev_abs = e->abs;
            M.writes++;
            mq_r++;
            continue;
        }

        /* the box: keep it AHEAD cycles in front of the beam */
        const double beam = m_abs(now);
        const uint64_t box = stbox_core_total_cyc();
        if ((double)box < beam + g_ahead && gap > boxrun) {
            if ((double)box < beam) M.box_behind++;
            const uint64_t s0 = ticks();
            /* owe it exactly one slice: we decide when it runs, so its
             * own clamp (drop debt past a frame) never loses time and a
             * box that fell behind after a stall catches up */
            if (box + 64 > g_synth) g_synth = box + 64;
            stbox_slice(g_synth);
            const double ns = (double)(ticks() - s0) * NSPT;
            if (ns > M.slice_max_ns) M.slice_max_ns = ns;
            M.box_ns += ns;
            M.box_slices++;
            continue;
        }

        if ((uint64_t)now >= next_poll && gap > pollg) {
            acia_poll();
            next_poll = (uint64_t)now + poll_every;
            continue;
        }

        if (gap > flushg) {
            const uint64_t f0 = ticks();
            const int did = flush_one();
            M.flush_ns += (double)(ticks() - f0) * NSPT;
            if (did) continue;
        }
    }

    g_report_stop = 1;
    pthread_join(rep, NULL);
    stbox_metal_hw = NULL; stbox_metal_line = NULL; stbox_metal_ikbd = NULL;
    stbox_core_disarm();
    ym_silence();
    bt_plain_screen();
    printf("\nstboxmetal done%s: %u frames, %llu writes (%llu over 1 us late), %llu RAM longs\n",
           g_stop ? " (Ctrl+C)" : "", stbox_shared.frame, (unsigned long long)M.writes,
           (unsigned long long)M.late1us, (unsigned long long)M.flushed);
    return 0;
}
