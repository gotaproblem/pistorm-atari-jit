static void m_resolve(const char *base, const char *file, char *out, size_t n)
{
    char b[512];
    while (*file == ' ' || *file == '\t') file++;
    if (file[0] == '~' && (file[1] == '/' || !file[1])) { snprintf(out, n, "%s%s", m_home(), file + 1); return; }
    if (file[0] == '/' || !base[0]) { snprintf(out, n, "%s", file); return; }
    if (base[0] == '~' && (base[1] == '/' || !base[1])) snprintf(b, sizeof b, "%s%s", m_home(), base + 1);
    else snprintf(b, sizeof b, "%s", base);
    const size_t L = strlen(b);
    snprintf(out, n, "%s%s%s", b, (L && b[L - 1] == '/') ? "" : "/", file);
}
/* "3:img" / "3 img" -> 3; "A:img" / "B:img" too when letters is set */
static const char *m_slot(const char *v, int *slot, int letters)
{
    *slot = -1;
    while (*v == ' ' || *v == '\t') v++;
    int d = -1;
    if (v[0] >= '0' && v[0] <= '7') d = v[0] - '0';
    else if (letters && (v[0] == 'A' || v[0] == 'a')) d = 0;
    else if (letters && (v[0] == 'B' || v[0] == 'b')) d = 1;
    if (d >= 0 && (v[1] == ':' || v[1] == ' ' || v[1] == '\t')) {
        *slot = d; v += 2;
        while (*v == ' ' || *v == '\t') v++;
    }
    return v;
}
static int m_word_is(const char *v, const char *const *w)
{
    char s[16]; int n = 0;
    while (*v == ' ' || *v == '\t') v++;
    while (v[n] && v[n] != ' ' && v[n] != '\t' && n < 15) { s[n] = (char)tolower((unsigned char)v[n]); n++; }
    s[n] = 0;
    for (; *w; w++) if (!strcmp(s, *w)) return 1;
    return 0;
}
static const char *const k_true[]  = { "1", "on", "yes", "true", "enabled", "enable", NULL };
static const char *const k_false[] = { "0", "off", "no", "false", "disabled", "disable", NULL };
static int m_bool(const char *v)                   /* present = on, as the emulator */
{
    return v && !m_word_is(v, k_false);
}

/* 0 = loaded; prints why not */
static int m_load_cfg(const char *path, const char *build, const char **tos)
{
    if (sc_load(&g_cfg, path) != 0) { printf("%s: cannot read\n", path); return -1; }
    char sec[SC_SEC_LEN];
    snprintf(sec, sizeof sec, "%s", build);
    for (char *p = sec; *p; p++) *p = (char)tolower((unsigned char)*p);
    int found = 0;
    for (int i = 0; i < g_cfg.n; i++) {
        const struct sc_line *l = &g_cfg.line[i];
        if (!strcmp(l->sec, sec)) found = 1;
        char *dst = !strcasecmp(l->key, "rom_path") ? g_rom_path :
                    !strcasecmp(l->key, "disk_path") ? g_disk_path :
                    !strcasecmp(l->key, "fdd_path") ? g_fdd_path : NULL;
        if (dst) {                       /* the last one wins, as there */
            const char *v = l->text;
            while (*v == ' ' || *v == '\t') v++;
            while (*v && *v != ' ' && *v != '\t') v++;
            while (*v == ' ' || *v == '\t') v++;
            snprintf(dst, 512, "%s", v);
            size_t L = strlen(dst);
            while (L && (dst[L - 1] == ' ' || dst[L - 1] == '\t' || dst[L - 1] == '\r')) dst[--L] = 0;
        }
    }
    if (!found) { printf("%s: no build [%s]\n", path, sec); return -1; }
    { const char *lv = sc_get(&g_cfg, sec, "metal_log"); if (lv && !strncasecmp(lv, "full", 4)) g_log = 1; }
    if (g_log) printf("config %s, build [%s]\n", path, sec);

    const char *v;
    if ((v = sc_get(&g_cfg, sec, "machine")) && !m_word_is(v, (const char *const[]){ "st", "stf", "stfm", NULL }))
        printf("  machine %s: the metal box is a plain ST - running it as one\n", v);
    if ((v = sc_get(&g_cfg, sec, "rom"))) { m_resolve(g_rom_path, v, g_tos_buf, sizeof g_tos_buf); *tos = g_tos_buf; }
    g_fastboot = m_bool(sc_get(&g_cfg, sec, "fastboot"));
    if ((v = sc_get(&g_cfg, sec, "usb")) && m_word_is(v, k_false)) g_pads = 0;
    /* a number fixes it; `measure` measures at every start; no key: the
     * value this Pi measured before, from stboxmetal.cal (m_cal_load) */
    if ((v = sc_get(&g_cfg, sec, "metal_cal"))) {
        if (!strncasecmp(v, "measure", 7)) g_cal_measure = 1; else { g_cal = atof(v); cal_forced = 1; }
    }
    if ((v = sc_get(&g_cfg, sec, "metal_vdec"))) {
        if (!strncasecmp(v, "measure", 7)) g_vdec_measure = 1; else { g_vdec = atof(v); vdec_forced = 1; }
    }
    {   /* the cache sits beside the config file */
        const char *sl = strrchr(path, '/');
        if (sl) snprintf(g_cal_file, sizeof g_cal_file, "%.*s/stboxmetal.cal", (int)(sl - path), path);
        else    snprintf(g_cal_file, sizeof g_cal_file, "stboxmetal.cal");
    }
    if ((v = sc_get(&g_cfg, sec, "metal_log")) && !strncasecmp(v, "full", 4)) g_log = 1;
    if ((v = sc_get(&g_cfg, sec, "stram_size")))
        printf("  stram_size ignored: the box has the real ST's RAM\n");

    /* floppies: every fdd line is a disk for Ctrl+Alt+F1..; drive A's first */
    {
        const int nf = sc_count(&g_cfg, sec, "fdd");
        int a_first = -1;
        for (int i = 0; i < nf && g_ndisks < 10; i++) {
            int drv;
            const char *img = m_slot(sc_get_n(&g_cfg, sec, "fdd", i), &drv, 1);
            if (!*img) continue;
            m_resolve(g_fdd_path, img, g_disk_buf[g_ndisks], sizeof g_disk_buf[0]);
            if (drv == 0 && a_first < 0) a_first = g_ndisks;
            g_disks[g_ndisks] = g_disk_buf[g_ndisks];
            g_ndisks++;
        }
        if (a_first > 0) { char *t = g_disks[0]; g_disks[0] = g_disks[a_first]; g_disks[a_first] = t; }
    }

    /* IDE: `ide` switches it on, `hdd [N:]image` fills slots, `hdd_order` */
    if (m_bool(sc_get(&g_cfg, sec, "ide"))) {
        const int nh = sc_count(&g_cfg, sec, "hdd");
        int next = 0, any = 0;
        for (int i = 0; i < nh; i++) {
            int slot;
            const char *img = m_slot(sc_get_n(&g_cfg, sec, "hdd", i), &slot, 0);
            if (slot < 0) slot = next < 8 ? next++ : -1;
            if (slot < 0 || !*img) continue;
            char p[512];
            m_resolve(g_disk_path, img, p, sizeof p);
            set_hard_drive_image_file_atari((uint8_t)slot, p);
            if (g_log) printf("  IDE slot %d: %s\n", slot, p);
            any = 1;
        }
        const int no = sc_count(&g_cfg, sec, "hdd_order");
        for (int i = 0; i < no; i++) {
            int slot;
            const char *m = m_slot(sc_get_n(&g_cfg, sec, "hdd_order", i), &slot, 0);
            const int mode = disk_order_parse_mode(m);
            if (slot >= 0 && mode >= 0) disk_order_set_hdd(slot, mode);
        }
        if (any) g_ide_on = 1;
    }

    /* ACSI: `acsi enabled` is the switch; other acsi lines are [N:]images */
    {
        const int na = sc_count(&g_cfg, sec, "acsi");
        int on = 0;
        for (int i = 0; i < na; i++) {
            const char *a = sc_get_n(&g_cfg, sec, "acsi", i);
            if (m_word_is(a, k_true)) on = 1;
            else if (m_word_is(a, k_false)) on = 0;
        }
        const int no = sc_count(&g_cfg, sec, "acsi_order");
        for (int i = 0; i < no; i++) {
            int id;
            const char *m = m_slot(sc_get_n(&g_cfg, sec, "acsi_order", i), &id, 0);
            const int mode = disk_order_parse_mode(m);
            if (id >= 0 && mode >= 0) disk_order_set_acsi(id, mode);
        }
        if (on)
            for (int i = 0; i < na; i++) {
                const char *a = sc_get_n(&g_cfg, sec, "acsi", i);
                if (m_word_is(a, k_true) || m_word_is(a, k_false)) continue;
                int id;
                const char *img = m_slot(a, &id, 0);
                char p[512];
                m_resolve(g_disk_path, img, p, sizeof p);
                if (acsi_attach_at(id, p) == 0) printf("  ACSI %d: %s\n", id, p);
                else                             printf("  ACSI %s: NOT attached\n", p);
            }
        if (on && acsi_enabled()) g_acsi_on = 1;
    }
    g_from_cfg = 1;
    return 0;
}

static void m_disks_on(void)
{
    if (g_ide_on) {
        InitIDE();
        if (!IDE_enabled) { g_ide_on = 0; printf("IDE: no image attached\n"); }
    }
    if (g_ide_on) { stbox_ide_read = m_ide_read; stbox_ide_write = m_ide_write; }
    if (g_acsi_on) stbox_acsi = &m_acsi_ops;
    if (g_ide_on || g_acsi_on) stbox_disk_irq = m_disk_irq;
}

static void m_disk(int i)
{
    if (i < 0 || i >= g_ndisks) return;
    uint32_t sz = 0;
    uint8_t *img = disk_load(g_disks[i], &sz);
    if (!img) return;
    stbox_core_disarm();                        /* adopt synchronously     */
    uint8_t *old = stbox_core_disk_insert(img, sz);
    free(old);
    stbox_core_arm(g_synth, ST_HZ);
    printf("[METAL] drive A: %s\n", g_disks[i]);
}

int main(int argc, char **argv)
{
    const char *tos = "/home/pistorm/roms/tos104uk.rom";
    double cal_secs = 5.0;
    int core = 3;
    const char *cfg = NULL, *build = NULL;
    for (int i = 1; i < argc; i++) {
        if (!strcmp(argv[i], "--config") && i + 1 < argc) cfg = argv[++i];
        else if (!strcmp(argv[i], "--build") && i + 1 < argc) build = argv[++i];
        else if (!strcmp(argv[i], "--tos") && i + 1 < argc) tos = argv[++i];
        else if (!strcmp(argv[i], "--disk") && i + 1 < argc) { if (g_ndisks < 10) g_disks[g_ndisks++] = argv[++i]; else i++; }
        else if (!strcmp(argv[i], "--cal") && i + 1 < argc) { g_cal = atof(argv[++i]); cal_forced = 1; }
        else if (!strcmp(argv[i], "--cal-secs") && i + 1 < argc) cal_secs = atof(argv[++i]);
        else if (!strcmp(argv[i], "--vdec") && i + 1 < argc) { g_vdec = atof(argv[++i]); vdec_forced = 1; }
        else if (!strcmp(argv[i], "--ahead") && i + 1 < argc) g_ahead = atoi(argv[++i]);
        else if (!strcmp(argv[i], "--core") && i + 1 < argc) core = atoi(argv[++i]);
        else if (!strcmp(argv[i], "--log") && i + 1 < argc) g_log = !strncmp(argv[++i], "full", 4);
        else {
            fprintf(stderr, "usage: %s [--config psctrl.cfg --build SECTION] [--tos ROM] [--disk IMG]...\n"
                            "       [--cal CYCLES | --cal-secs S] [--vdec CYCLE] [--ahead CYCLES] [--core N] [--log quiet|full]\n", argv[0]);
            return 2;
        }
    }
    setvbuf(stdout, NULL, _IOLBF, 0);
    psctrl_tunables_init();                    /* PISTORM_IDE_TRACE, PISTORM_ACSI_DEBUG, ... */
    if (cfg || build) {
        if (!cfg || !build) { printf("--config and --build go together\n"); return 2; }
        if (m_load_cfg(cfg, build, &tos) != 0) return 2;
    }

    /* ROM and RAM before the bus: a bad path costs nothing */
    static uint8_t rom[512 * 1024];
    FILE *f = fopen(tos, "rb");
    if (!f) { printf("%s: %s\n", tos, strerror(errno)); return 2; }
    size_t rsz = fread(rom, 1, sizeof rom, f);
    fclose(f);
    if (g_fastboot) m_fastboot(rom, (int)rsz);
    m_disks_on();

    if (bt_init("stboxmetal", core)) return 1;
    g_ram_bytes = scr.bank0 + scr.bank1;
    if (g_ram_bytes != (512u << 10) && g_ram_bytes != (1024u << 10) &&
        g_ram_bytes != (2048u << 10) && g_ram_bytes != (4096u << 10)) {
        printf("ST-RAM %u K is not a size the box models (512 K, 1, 2, 4 MB)\n", g_ram_bytes >> 10);
        return 1;
    }
    uint8_t *ram = calloc(1, g_ram_bytes + 32768);
    g_dirty = calloc(g_ram_bytes / 256, sizeof *g_dirty);
    g_blk = calloc(g_ram_bytes / 16384 + 1, 1);
    if (!ram || !g_dirty || !g_blk) { printf("out of memory\n"); return 1; }
    stbox_shared.ram = ram; stbox_shared.ram_size = g_ram_bytes;
    stbox_core_set_machine(0);
    if (stbox_core_setup(ram, g_ram_bytes, rom, (uint32_t)rsz)) { printf("box setup failed (ROM?)\n"); return 1; }
    if (g_ndisks) {
        uint32_t sz = 0;
        uint8_t *img = disk_load(g_disks[0], &sz);
        if (img) { stbox_core_disk_insert(img, sz); if (g_log) printf("drive A: %s\n", g_disks[0]); }
    }
    if (g_log) printf("box: TOS %s, %u K\n", tos, g_ram_bytes >> 10);
    bt_quiet = !g_log;

    m_cal_load();
    const int measured_any = !cal_forced || !vdec_forced;

    /* calibrate the write landing, as beamtest's B */
    if (g_log) printf("\n[A] LOCK\n");
    if (lock(g_log ? 0 : 2) != 0) return 1;
    measure_writes();
    if (!cal_forced) {
        if (g_log) printf("\n[B] RIGHT BORDER SWEEP (calibration, %.0f s)\n", cal_secs);
        else       printf("[METAL] measuring the write calibration on this Pi (%.0f s, once)\n", 2 * cal_secs);
        run_phase(PH_RIGHT, cal_secs);
        if (g_log) { report_common(); report_sweep(1); }
        bt_calibrate_from_sweep(cal_secs);
    } else if (g_log)
        printf("calibration %+.2f cycles (--cal)\n", g_cal);
    if (!vdec_forced) {
        if (g_log) printf("\n[F] VERTICAL DECISION SWEEP (%.0f s)\n", cal_secs);
        else       printf("[METAL] measuring the vertical decision on this Pi (%.0f s, once)\n", cal_secs);
        lock(g_log ? 1 : 2);
        run_phase(PH_VSWEEP, cal_secs);
        /* the first 50 Hz cycle from which top and bottom together open
         * at least half the time, every later one too (the 50 % point of
         * the step): the decision is the cycle before it */
        int first = -1;
        for (int i = VS_N - 1; i >= 0; i--) {
            const double t = R.vs_n[i] ? (double)R.vs_top[i] / R.vs_n[i] : 0.0;
            const double b = R.vs_n[i] ? (double)R.vs_bot[i] / R.vs_n[i] : 0.0;
            if (t + b >= 1.0) first = 496 + i; else break;
        }
        for (int i = 0; i < VS_N && g_log; i++)
            printf("  50 Hz back at %d: top opened %5.1f %%, bottom %5.1f %% (%u frames)\n", 496 + i,
                   R.vs_n[i] ? 100.0 * R.vs_top[i] / R.vs_n[i] : 0.0,
                   R.vs_n[i] ? 100.0 * R.vs_bot[i] / R.vs_n[i] : 0.0, R.vs_n[i]);
        if (first > 496) g_vdec = first - 1;
        if (first <= 496) g_vdec_failed = 1;
        if (g_log || first <= 496)
            printf("  vertical decision: %s cycle %.0f (box model 502)\n",
                   first > 496 ? "real ST at" : "NOT FOUND - using", g_vdec);
        bt_plain_screen();
    } else if (g_log)
        printf("vertical decision %.0f (--vdec)\n", g_vdec);

    if (measured_any && !g_cal_measure && !g_vdec_measure) {
        if (bt_cal_failed || g_vdec_failed)
            printf("[METAL] the %s measurement failed: not saved, it is measured again next start\n",
                   bt_cal_failed ? "write calibration" : "vertical decision");
        else
            m_cal_save();
    }

    /* hand the machine to the box */
    M_INIT();
    stbox_metal_hw = m_hw;
    stbox_metal_line = m_line;
    stbox_metal_ikbd = m_ikbd;
    stbox_metal_dirty = g_dirty;
    stbox_metal_blk = g_blk;
    ilog_t0 = ticks();
    acia_init();
    if (m_start_box() != 0) return 1;
    if (g_log) {
        printf("\n[METAL] running: Ctrl+Alt+Undo %s, Ctrl+Alt+F1..F%d disks, Ctrl+Alt+Help frame capture, Ctrl+Alt+Shift+Undo quit\n",
               g_from_cfg ? "setup page" : "reset", g_ndisks ? g_ndisks : 1);
        if (g_ide_on || g_acsi_on) printf("[METAL] hard disks:%s%s\n", g_ide_on ? " IDE" : "", g_acsi_on ? " ACSI" : "");
    } else {
        const char *tn = strrchr(tos, '/');
        printf("[METAL] running %s, %u K%s%s%s%s | ST clock %.0f Hz, calibration %+.2f, vertical decision %.1f\n",
               tn ? tn + 1 : tos, g_ram_bytes >> 10, g_ide_on ? ", IDE" : "", g_acsi_on ? ", ACSI" : "",
               g_ndisks ? ", A: " : "", g_ndisks ? (strrchr(g_disks[0], '/') ? strrchr(g_disks[0], '/') + 1 : g_disks[0]) : "",
               FRAME_CYC * HZ / P, g_cal, g_vdec);
        printf("[METAL] keys: Ctrl+Alt+Undo %s, Ctrl+Alt+F1..F%d disks, Ctrl+Alt+Help capture, Ctrl+Alt+Shift+Undo quit\n",
               g_from_cfg ? "setup page" : "reset", g_ndisks ? g_ndisks : 1);
    }
    pthread_t rep, padt;
    pthread_create(&rep, NULL, reporter, NULL);
    pthread_create(&padt, NULL, pad_thread, NULL);   /* pads (unless usb off), keyboards, mice */

    const double guard = GUARD_NS / NSPT, boxrun = BOXRUN_NS / NSPT,
                 flushg = FLUSH_NS / NSPT, pollg = POLL_NS / NSPT;
    const uint64_t poll_every = (uint64_t)(ACIA_POLL_US * 1000.0 / NSPT);
    uint64_t next_poll = ticks();

#ifdef BEAMTEST_SIM
    const char *trs = getenv("SIM_RESET_S");          /* test the reset path */
    uint64_t test_reset_at = trs ? ticks() + (uint64_t)(atof(trs) * HZ) : 0;
    const char *tfc = getenv("SIM_FCAP_S");
    uint64_t fcap_at = tfc ? ticks() + (uint64_t)(atof(tfc) * HZ) : 0;
    const char *tcr = getenv("SIM_CRASH_S");
    uint64_t crash_at = tcr ? ticks() + (uint64_t)(atof(tcr) * HZ) : 0;
    const char *sim_in = getenv("SIM_INPUT");
    const uint64_t sim_t0 = ticks();
    const char *tsh = getenv("SIM_SHOT_S");           /* SIM_SHOT=file.pgm */
    uint64_t shot_at = (tsh && getenv("SIM_SHOT")) ? ticks() + (uint64_t)(atof(tsh) * HZ) : 0;
#endif
    while (!g_stop && !g_want_quit) {
#ifdef BEAMTEST_SIM
        if (test_reset_at && ticks() > test_reset_at) { test_reset_at = 0; g_want_reset = 1; }
        if (sim_in && *sim_in) {                       /* SIM_INPUT="secs:j1=80 secs:k=39 ..." */
            const double at = atof(sim_in);
            if ((double)(ticks() - sim_t0) >= at * HZ) {
                const char *c = strchr(sim_in, ':');
                if (c) {
                    unsigned v = 0;
                    if (c[1] == 'j' && sscanf(c + 3, "=%x", &v) == 1) stbox_joy_event(c[2] - '0', (uint8_t)v);
                    else if (c[1] == 'k' && sscanf(c + 2, "=%x", &v) == 1) {
                        stbox_key_event(v & 0x7F, !(v & 0x80));
                    }
                    printf("[sim] input %.*s\n", (int)strcspn(sim_in, " "), sim_in);
                }
                sim_in += strcspn(sim_in, " ");
                while (*sim_in == ' ') sim_in++;
            }
        }
        if (fcap_at && ticks() > fcap_at) { fcap_at = 0; FC.req = 1; }
        if (crash_at && ticks() > crash_at) {          /* test the halt report */
            crash_at = 0;
            m68k_set_reg(M68K_REG_SP, 0xD00100);
            m68k_set_reg(M68K_REG_PC, 0xD00000);
        }
        if (shot_at && ticks() > shot_at) {           /* the box's screen, as a PGM */
            shot_at = 0;
            const uint32_t base = (stbox_bus_r8(0xFF8201) << 16) | (stbox_bus_r8(0xFF8203) << 8);
            const int rez = stbox_bus_r8(0xFF8260) & 3;
            const int w = rez ? 640 : 320, h = rez == 2 ? 400 : 200, planes = rez == 0 ? 4 : rez == 1 ? 2 : 1;
            FILE *o = fopen(getenv("SIM_SHOT"), "wb");
            fprintf(o, "P5 %d %d 15\n", w, h);
            for (int y = 0; y < h; y++)
                for (int x = 0; x < w; x++) {
                    const uint32_t wa = base + (uint32_t)y * 160 + (uint32_t)(x / 16) * planes * 2;
                    int c = 0;
                    for (int pl = 0; pl < planes; pl++) {
                        const uint16_t wd = (uint16_t)((stbox_shared.ram[wa + pl * 2] << 8) | stbox_shared.ram[wa + pl * 2 + 1]);
                        c |= ((wd >> (15 - (x & 15))) & 1) << pl;
                    }
                    fputc(planes == 1 ? (c ? 0 : 15) : 15 - c * (planes == 2 ? 5 : 1), o);
                }
            fclose(o);
            printf("[sim] screen base %06X rez %d -> %s\n", base, rez, getenv("SIM_SHOT"));
        }
#endif
        if (g_want_reset && g_from_cfg) {        /* back to the setup page */
            g_relaunch = 1;
            break;
        }
        if (g_want_reset) {
            g_want_reset = 0; M.resets++;
            printf("[METAL] cold reset\n");
            if (m_start_box() != 0) break;
            continue;
        }
        if (g_want_disk >= 0) { int d = g_want_disk; g_want_disk = -1; m_disk(d); continue; }

        const double now = (double)ticks();
        if (FC.req && !FC.state) { FC.req = 0; FC.arm_frame = stbox_shared.frame; FC.state = 1; }
        if (FC.state >= 2) {
            fc_check(now);
            if (FC.state == 3) {                       /* the box published it */
                const uint32_t ci = stbox_shared.cap_idx;
                FC.have_pic = ci < STBOX_CAP_BUFS;
                if (FC.have_pic) memcpy(&FC.pic, &stbox_cap[ci], sizeof FC.pic);
#ifdef BEAMTEST_SIM
                { FILE *rf = fopen("/tmp/mt/fcap.ram", "wb"); fwrite(stbox_shared.ram, 1, g_ram_bytes, rf); fclose(rf);
                  printf("[sim] MFP:");
                  for (uint32_t r = 0xFFFA01; r <= 0xFFFA25; r += 2) printf(" %02X", stbox_bus_r8(r));
                  printf("  vectors: hbl %08X vbl %08X tb %08X\n", stbox_bus_r32(0x68), stbox_bus_r32(0x70), stbox_bus_r32(0x120)); }
#endif
                FC.state = 4;
            } else if (FC.state == 4 && FC.chk >= FC.nl) {
                int pending = 0;                       /* its writes all out? */
                for (unsigned j = mq_r; j != mq_w && !pending; j++) pending = mq[j & (MQ - 1)].cap;
                if (!pending) FC.state = 5;
            }
        }
        /* the next timed thing: a queued write or the lock read */
        double tn = 1e30; int is_probe = 0;
        if (mq_r != mq_w) {
            const mev_t *e = &mq[mq_r & (MQ - 1)];
            tn = m_time((double)e->abs + g_cal) - (e->size == 1 ? LEAD8 : LEAD16);
        }
        if (P1.pending) {
            const double tp = m_time((double)P1.abs) - g_plead_ns / NSPT;
            if (tp < tn) { tn = tp; is_probe = 1; }
        }
        for (int k = 0; k < 2; k++)
            if (PV[k].pending) {
                const double tp = m_time((double)PV[k].abs);
                if (tp < tn) { tn = tp; is_probe = 2 + k; }
            }
        const double gap = tn - now;

        if (gap < guard) {
            const uint64_t w0 = ticks();
            if ((double)w0 < tn) g_act = 0;
            while ((double)ticks() < tn) ;
            M.wait_ns += (double)(ticks() - w0) * NSPT;
            if (is_probe) {
                const uint64_t p0 = ticks();
                if (is_probe == 1) m_probe(); else v_probe(is_probe - 2);
                act(4, p0);
                if (g_act_ns > M.probe_max_ns) M.probe_max_ns = g_act_ns;
                continue;
            }
            const mev_t *e = &mq[mq_r & (MQ - 1)];
            const uint64_t t0 = ticks();
            if (e->size == 1) ps_write_8(e->a, e->v);
            else              ps_write_16(e->a, e->v);
            const double late = ((double)t0 - tn) * NSPT;
            /* a write within 16 cycles of the one before is a burst (movem
             * to the palette): our bus write is ~0.7 us against the
             * 68000's 0.5, so a burst falls behind by design. The lateness
             * that matters for raster tricks is that of the others. */
            static uint64_t prev_abs;
            const int burst = e->abs - prev_abs < 16;
            if (burst) {
                M.burst++;
                if (late > M.burst_late_max_ns) M.burst_late_max_ns = late;
            } else {
                if (late > 1000.0) {
                    M.late1us++;
                    M.late_by[g_act]++;
                    if (g_act_ns > M.late_by_ns[g_act]) M.late_by_ns[g_act] = g_act_ns;
                }
                if (late > M.late_max_ns) M.late_max_ns = late;
            }
            prev_abs = e->abs;
            if (e->a == 0xFF820A || e->a == 0xFF8260) {
                xw_t *x = &xw[xw_n++ & (XW - 1)];
                x->abs = e->abs; x->a = (uint8_t)e->a; x->v = (uint8_t)e->v;
                x->late10 = (int16_t)(late / 10.0 > 32000 ? 32000 : late / 10.0);
            }
            if (e->cap && FC.nw < CW)
                FC.w[FC.nw++] = (cw_t){ e->line, e->lcyc, e->a, e->v, (uint8_t)burst,
                                        (int32_t)late, e->pc };
            M.writes++;
            mq_r++;
            act(5, t0);
            continue;
        }

        /* the box: keep it AHEAD cycles in front of the beam */
        const double beam = m_abs(now);
        const uint64_t box = stbox_core_total_cyc();
        /* a halted box never moves on: slicing it would take every
         * turn of this loop, and the keyboard - Ctrl+Alt+Undo - with it */
        if ((double)box < beam + g_ahead && gap > boxrun && !stbox_core_halted()) {
            if ((double)box < beam) M.box_behind++;
            const uint64_t s0 = ticks();
            /* owe it exactly one slice: we decide when it runs, so its
             * own clamp (drop debt past a frame) never loses time and a
             * box that fell behind after a stall catches up */
            if (box + 64 > g_synth) g_synth = box + 64;
            stbox_slice(g_synth);
            const double ns = (double)(ticks() - s0) * NSPT;
            g_act = 1; g_act_ns = ns;
            if (ns > M.slice_max_ns) M.slice_max_ns = ns;
            M.box_ns += ns;
            M.box_slices++;
            continue;
        }

        if ((uint64_t)now >= next_poll && gap > pollg) {
            const uint64_t a0 = ticks();
            padq_drain();
            acia_poll();
            act(3, a0);
            if (g_act_ns > M.poll_max_ns) M.poll_max_ns = g_act_ns;
            next_poll = (uint64_t)now + poll_every;
            continue;
        }

        if (gap > flushg) {
            const uint64_t f0 = ticks();
            const int did = flush_one();
            M.flush_ns += (double)(ticks() - f0) * NSPT;
            if (did) {
                act(2, f0);
                if (g_act_ns > M.flush_max_ns) M.flush_max_ns = g_act_ns;
            }
            if (did) continue;
        }
    }

    g_report_stop = 1; g_pad_stop = 1;
    pthread_join(rep, NULL);
    pthread_join(padt, NULL);
    stbox_metal_hw = NULL; stbox_metal_line = NULL; stbox_metal_ikbd = NULL;
    stbox_core_disarm();
    ym_silence();
    bt_plain_screen();
    printf("\nstboxmetal done%s: %u frames, %llu writes (%llu over 1 us late), %llu RAM longs\n",
           g_stop ? " (Ctrl+C)" : "", stbox_shared.frame, (unsigned long long)M.writes,
           (unsigned long long)M.late1us, (unsigned long long)M.flushed);
    if (g_relaunch) { printf("[METAL] Ctrl+Alt+Undo: back to the setup page (exit 42)\n"); return 42; }
    return 0;
}
